#![no_std]
#![no_main]

use shadow_rs::shadow;
shadow!(build);

mod task_orchestration;

use defmt::{error, info};
// RTT остаётся дефолтным транспортом в обоих профилях — сырой шаблон не знает,
// какой конкретный USART на плате пользователь отведёт под лог без пробника.
// Паттерн замены (UART, без RTT/пробника) для release — doc-комментарий в
// task_orchestration.rs, подключается по мере готовности платы (Board должен
// будет отдавать реальную периферию под транспорт).
use defmt_rtt as _;

use embassy_executor::Spawner;

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    // Первая же строка лога отвечает на вопрос «а что вообще залито в плату»:
    // версия пакета и коммит, из которого собран образ (их подставляет
    // `shadow-rs` в build.rs). Без этого build-info собиралась впустую, а по
    // OTA легко получить плату с прошивкой, происхождение которой неизвестно.
    // `host-target-tests` ждёт именно этот баннер.
    info!(
        "app: starting {} ({})",
        build::PKG_VERSION,
        build::SHORT_COMMIT
    );

    // Причина прошлого падения, если оно было: панический хендлер ниже успел
    // записать её в регион PANIC, а тот пережил сброс (RAM, но вне секций,
    // которые cortex-m-rt инициализирует при старте). Читается один раз —
    // `panic-persist` стирает свою магию, — поэтому печатать надо сразу и
    // до всего остального: следующий сброс эту строку уже не покажет.
    if let Some(reason) = panic_persist::get_panic_message_utf8() {
        error!("app: предыдущий запуск упал: {}", reason);
    }

    let mut _board = bsp::Board::init();
}

/// Единственный паникёр бинарника: сохранить причину и напечатать её.
///
/// `panic-probe` (стоял здесь раньше) умел только второе, а причина нужна и
/// тогда, когда пробника рядом нет — это и есть смысл региона PANIC. Обратное
/// тоже верно: голого `panic-persist` мало, его штатный хендлер молча
/// сохраняет и сбрасывает МК, так что при подключённом пробнике падение
/// выглядит как самопроизвольный перезапуск. Поэтому фича
/// `custom-panic-handler` и эти несколько строк.
#[panic_handler]
fn panic(info: &core::panic::PanicInfo) -> ! {
    // Дальше нас всё равно ждёт сброс или остановка, а прерывание посреди
    // записи дампа оставило бы в PANIC половину сообщения.
    cortex_m::interrupt::disable();

    // Сначала сохранить — печать может не дойти (нет пробника, RTT-буфер
    // переполнен), а дамп нужен именно в этом случае.
    panic_persist::report_panic_info(info);
    // `Display2Format` — мост от `core::fmt::Display` к defmt: `PanicInfo`
    // умеет только первое.
    error!("panic: {}", defmt::Display2Format(info));

    // Разное поведение по профилю — единственная такая развилка в шаблоне, и
    // она про то, кто смотрит на устройство. Под отладчиком полезнее
    // остановиться на месте падения (`udf` -> HardFault, пробник ловит его и
    // показывает стек); в поле полезнее вернуться в работу — причина уже
    // сохранена, и следующий старт напечатает её сам.
    #[cfg(debug_assertions)]
    cortex_m::asm::udf();
    #[cfg(not(debug_assertions))]
    cortex_m::peripheral::SCB::sys_reset()
}
