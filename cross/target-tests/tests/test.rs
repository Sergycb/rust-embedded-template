    /// Раздел `DFU` доступен на запись и чтение — то есть та половина OTA,
    /// которая не зависит от канала доставки, работает на этом чипе: адреса
    /// раздела посчитаны верно, стирание сектора проходит, записанное
    /// читается обратно.
    ///
    /// Проверяется на «настоящем» устройстве не случайно: границы раздела
    /// приходят из символов линкера, размер стираемой страницы — из
    /// метаданных чипа, и разъехаться они могут только здесь. `mark_updated`
    /// тест намеренно не зовёт — иначе следующий сброс поменял бы разделы
    /// местами прямо посреди прогона.
    #[test]
    fn dfu_partition_accepts_a_write(mut board: Board) {
        // Кратно WRITE_SIZE флеша: `write_firmware` короче не принимает.
        let written = [0xA5u8; 32];
        let mut read = [0x00u8; 32];

        board
            .ota
            .write(0, &written)
            .expect("раздел DFU должен принимать запись");
        board
            .ota
            .read(0, &mut read)
            .expect("раздел DFU должен читаться");

        assert_eq!(written, read);
    }
