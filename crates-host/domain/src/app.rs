//! Узел `APP` графа задач: каркас под работу вашего устройства.
//!
//! Задача живёт здесь, а не рядом с графом в `crates-cross/app`, по общему
//! правилу проекта: граф — это оркестрация (кто кого спавнит, что делать с
//! упавшим узлом, чем кормить сторож), а то, что узел делает, — логика.
//! Логика тестируется на хосте и про чип не знает.
//!
//! Связь с графом держится на проекции аргументов `supervisor_graph!`
//! (`task: domain::app::run(&ctx.heartbeat)`): при ней макрос не генерирует
//! тип контекста, а раскладывает поля по обычным параметрам — поэтому
//! сигнатура ниже не называет ни одного типа из крейта, где объявлен граф, и
//! функция может лежать в другом крейте вовсе. Именно так устроен и пример в
//! самом `supervisor` (`supervisor-logic-fixture`).

use defmt_or_log::info;
use embassy_time::{Duration, Timer};
use supervisor::Heartbeat;
use supervisor::runtime::TaskExit;

/// Период холостого цикла — он же период отметок у сторожа.
const IDLE_PERIOD: Duration = Duration::from_millis(500);

/// Единственный узел графа — каркас под вашу работу.
///
/// Здесь он только сообщает о старте и отмечается у сторожа в холостом цикле.
/// Это осознанно: шаблон не знает, что должно делать ваше устройство, а
/// периодический лог в пустом узле опаснее, чем кажется — `probe-rs attach`
/// переводит RTT-канал в режим «блокировать при заполнении», и после
/// отключения пробника прошивка встала бы внутри критической секции. Поэтому
/// цикл молчит.
///
/// **`feed()` зовётся явно и только после реального прогресса** — здесь
/// прогресса нет, поэтому отметка стоит рядом с таймером. Когда в цикле
/// появится работа, отметку ставьте ПОСЛЕ неё, а не до: автоматического
/// «задача жива, раз её future опрашивают» тут нет намеренно, иначе сторож
/// сторожил бы исполнитель, а не полезную работу.
///
/// Возвращаемый `TaskExit` — то, что граф делает с закончившимся прогоном
/// (`restart:`/`backoff:` узла). Цикл ниже не кончается никогда, так что
/// значение недостижимо; у задачи, которая может закончиться, `Completed`
/// против `Failed` решает, перезапустят её или нет.
///
/// Что дальше: замените тело на свой цикл, добавьте узлам `deps:` (порядок
/// старта), `inbox:` (очередь событий), `resources:` (ручка периферии,
/// переживающая перезапуск задачи) — всё это описано в
/// `docs/modules/app-graph.md`.
pub async fn run(heartbeat: &Heartbeat<'_>) -> TaskExit {
    info!("domain: узел APP запущен");
    loop {
        // Здесь ваша работа.
        heartbeat.feed();
        Timer::after(IDLE_PERIOD).await;
    }
}

// Узел графа объявлен здесь же, где лежит его задача: подсистема сама говорит,
// сколько ей нужно узлов и с какими зависимостями, а граф в
// `crates-cross/app/src/graph.rs` только собирает объявленное вместе со всем,
// что знает про железо (`boot:`, `watchdog:`).
//
// `supervisor_fragment!` объявляет СРЕЗ графа: раскрывается он в один
// `#[macro_export] macro_rules!`-ретранслятор и больше ни во что — ни задач,
// ни статиков, ни `spawn_all`. Отсюда два следствия, оба важные:
//
// * Ретранслятор виден по пути от корня крейта — `::domain::APP_FRAG`, как бы
//   глубоко ни лежал этот модуль. Имя `APP_FRAG` compose-site и называет в
//   своём `fragments: [..]`.
// * Токены ниже резолвятся НЕ здесь, а на compose-site: так работает
//   `macro_rules!`. Поэтому `RestartPolicy`, `backoff()` и `APP_WATCHDOG`
//   обязаны быть в области видимости там, в `graph.rs`, — и это не оплошность,
//   а разделение: политика перезапуска и таймаут узла связаны с аппаратным
//   `bsp::wdg::HW_TIMEOUT_US` (цепочка `BACKOFF_MAX` < `APP_WATCHDOG` <
//   `HW_TIMEOUT_US`), значит цифрам место рядом с железом, а не здесь.
//   Забудете определить любое из имён — ошибка компиляции на compose-site.
//
// Путь к задаче, наоборот, пишется `$crate::` и указывает сюда: только эта
// форма переживает переименование зависимости в чужом манифесте
// (`logic = { package = "domain" }`), а `crate::` в теле `macro_rules!`
// означал бы крейт, который фрагмент ВЫЗЫВАЕТ.
supervisor::supervisor_fragment! {
    name: APP_FRAG;

    node APP, deps: [], restart: RestartPolicy::OnFailure, backoff: backoff(),
        watchdog: APP_WATCHDOG observe,
        task: $crate::app::run(&ctx.heartbeat);
}
