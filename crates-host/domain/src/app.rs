//! Узел `APP` графа задач: каркас под работу вашего устройства.
//!
//! Задача живёт здесь, а не рядом с графом в `crates-cross/app`, по общему
//! правилу проекта: граф — это оркестрация (кто кого спавнит, что делать с
//! упавшим узлом, чем кормить сторож), а то, что узел делает, — логика.
//! Логика тестируется на хосте и про чип не знает.
//!
//! Задача — автомат `#[fsm::typestate]` на контексте узла. Контекст
//! [`AppCtx`] эмитит фрагмент ниже (`ctx: $crate::app::AppCtx`) здесь же, в
//! `domain`, а не compose-site: поэтому сигнатура не называет ни одного типа
//! из крейта, где объявлен граф, и автомат с его действиями живёт рядом с
//! узлом. Так же устроен и пример в самом `supervisor`
//! (`supervisor-logic-fixture`).

use defmt_or_log::info;
use embassy_time::{Duration, Instant};
use supervisor::policy::{BackoffPolicy, JitterPolicy};
use supervisor::runtime::TaskExit;

/// Период холостого цикла — он же период отметок у сторожа.
const IDLE_PERIOD: Duration = Duration::from_millis(500);

/// Потолок паузы между перезапусками.
///
/// Вынесен в константу не ради читаемости: от него зависит [`WATCHDOG`], и
/// связь эту держит `const`-assert ниже — глазами её не увидеть, пока цифры
/// стоят в разных местах.
const BACKOFF_MAX: Duration = Duration::from_secs(5);

/// Политика пауз между перезапусками узла.
///
/// Значения намеренно скромные: первый повтор почти сразу, дальше удвоение до
/// [`BACKOFF_MAX`]. Смысл backoff'а не в том, чтобы «подождать подольше», а в
/// том, чтобы падающая задача не крутила рестарты в цикле, съедая процессор у
/// соседних узлов.
///
/// `const`, а не `fn`: `supervisor_graph!` кладёт политику каждого узла в
/// `static` в `.rodata`, и выражение в `backoff:` обязано вычисляться на
/// компиляции — не-`const` там ошибка сборки (`E0015`), а не тихие 72 байта
/// RAM в future узла, как было раньше.
pub const BACKOFF: BackoffPolicy = BackoffPolicy {
    first: Duration::from_millis(50),
    factor: 2,
    jitter: JitterPolicy::None,
    floor: Duration::from_millis(50),
    max: BACKOFF_MAX,
};

/// Сколько узлу позволено не отмечаться, прежде чем это будет замечено.
///
/// **Считается от [`BACKOFF_MAX`], а не от периода отметок узла** — и это
/// главное, что здесь легко испортить. Слот сторожа граф взводит ОДИН раз,
/// перед первой попыткой, и снимает только когда узел уходит насовсем; во
/// время паузы между перезапусками слот жив, а кормить его некому. Значит
/// самый длинный законный промежуток между отметками — не период работы
/// узла, а потолок backoff'а. Возьмите таймаут меньше — штатный перезапуск
/// начнёт выглядеть зависанием: с `observe` это ложная строка в логе, без
/// него — аппаратный сброс здоровой платы. Это звено держит `const`-assert
/// ниже.
///
/// Второе звено — с другого конца, и оно не здесь: `bsp::wdg::HW_TIMEOUT_US`
/// обязан быть больше этого значения плюс `WATCHDOG_CHECK_EVERY` графа
/// (`crates-cross/app/src/graph.rs`). Из этой пары `check_every` против
/// аппаратного таймаута проверяет сам `supervisor_graph!` (assert эмитит он,
/// читая `HARDWARE_TIMEOUT` у типа сторожа), а сумму с таймаутом узла —
/// `const`-assert в графе, потому что там видны оба конца; эта константа в
/// проверку `supervisor` не входит намеренно — `docs/watchdog.md`.
pub const WATCHDOG: Duration = Duration::from_secs(7);

// Левое звено цепочки таймаутов, проверенное компилятором: `<` на `Duration`
// в `const` не работает (нет const-трейтов), поэтому сравниваются тики.
const _: () = assert!(
    BACKOFF.max.as_ticks() < WATCHDOG.as_ticks(),
    "таймаут узла APP обязан быть больше потолка backoff'а: слот сторожа переживает паузу между \
     перезапусками, и кормить его в это время некому"
);

/// Единственный узел графа — каркас под вашу работу.
///
/// Здесь он только сообщает о старте и отмечается у сторожа в холостом цикле.
/// Это осознанно: шаблон не знает, что должно делать ваше устройство, а
/// периодический лог в пустом узле — это шум, вытесняющий из буфера RTT
/// строки, которые важны. Поэтому цикл молчит.
///
/// **`feed()` зовётся явно и только после реального прогресса** — здесь
/// прогресса нет, поэтому отметка стоит в действии такта. Когда появится
/// работа, отметку ставьте ПОСЛЕ неё, а не до: автоматического «задача жива,
/// раз её future опрашивают» тут нет намеренно, иначе сторож сторожил бы
/// исполнитель, а не полезную работу.
///
/// Возвращаемый `TaskExit` — то, что граф делает с закончившимся прогоном
/// (`restart:`/`backoff:` узла). У автомата нет выходного состояния, `run`
/// не возвращается никогда, так что значение недостижимо; у задачи, которая
/// может закончиться, выходное состояние (`exit Done { result: TaskExit }`,
/// как у [`ota`](crate::ota)) решает, перезапустят её или нет.
///
/// Что дальше: добавьте автомату состояния и строки переходов, узлу —
/// `deps:` (порядок старта), `inbox:` (очередь событий — источник в
/// `listen`), `resources:` (ручка периферии, переживающая перезапуск задачи)
/// — всё это описано в `docs/modules/app-graph.md`.
pub async fn run(mut ctx: AppCtx<'_>) -> TaskExit {
    match ctx.run().await {}
}

#[fsm::typestate]
impl AppCtx<'_> {
    fsm::machine! {
        machine App mod edges {
            states {
                /// Холостой ход: ждёт такт в `next`.
                Idle { next: Instant },
            }
            start => begin -> Idle;
            listen {
                Idle { next } => tick: fsm::deadline(*next),
            }
            transitions {
                Idle + tick(()) => idle -> self,
            }
        }
    }

    /// Сообщает о старте и назначает первый такт.
    fn begin(&mut self) -> Idle {
        info!("domain: узел APP запущен");
        Idle {
            next: Instant::now() + IDLE_PERIOD,
        }
    }

    /// Такт холостого хода: здесь ваша работа, отметка у сторожа — после неё.
    ///
    /// Следующий такт — `fsm::next_tick`, а не `Ticker`: отставший `Ticker`
    /// догоняет пачкой тиков подряд, и работа выполнилась бы N раз разом;
    /// `next_tick` пропущенные такты отбрасывает.
    fn idle(&mut self, s: &mut Idle) {
        self.heartbeat.feed();
        s.next = fsm::next_tick(s.next, IDLE_PERIOD, Instant::now());
    }
}

// Узел графа объявлен здесь же, где лежит его задача: фрагмент — законченный
// модуль с одной задачей, её политикой и таймаутом, а граф в
// `crates-cross/app/src/graph.rs` только перечисляет фрагменты и добавляет
// то, что знает про железо (`boot:`, блок `watchdog:`).
//
// `supervisor_fragment!` объявляет СРЕЗ графа: раскрывается он в один
// `#[macro_export] macro_rules!`-ретранслятор и больше ни во что — ни задач,
// ни статиков, ни `spawn_all`. Отсюда три следствия:
//
// * Ретранслятор виден по пути от корня крейта — `::domain::APP_FRAG`, как бы
//   глубоко ни лежал этот модуль. Имя `APP_FRAG` compose-site и называет в
//   своём `fragments: [..]`.
// * Узел не носит имени — его даёт запись `fragments:` (`APP_FRAG as APP`), и
//   тот же фрагмент, названный дважды под разными `as`, — два узла. Поэтому
//   ниже `node …` без имени, а «узел APP» в этом файле — про то, как его
//   зовёт граф шаблона.
// * Токены ниже резолвятся НЕ здесь, а на compose-site: так работает
//   `macro_rules!`. Поэтому всё, что фрагмент называет, написано полным путём
//   — `$crate::app::BACKOFF`, `::supervisor::policy::RestartPolicy` — и от
//   compose-site ничего не требует: голое имя (`BACKOFF`) искалось бы в
//   `graph.rs` и падало бы там с `E0425`. `$crate::` при этом указывает сюда
//   и переживает переименование зависимости в чужом манифесте
//   (`logic = { package = "domain" }`), а `crate::` в теле `macro_rules!`
//   означал бы крейт, который фрагмент ВЫЗЫВАЕТ.
//
// Единственное, что фрагмент требует от графа, — блок `watchdog:`: узел с
// полем `watchdog:` без него не компилируется, а сам блок — решение на весь
// граф (один аппаратный сторож, один `check_every`), и фрагменту его
// объявлять нельзя.
supervisor::supervisor_fragment! {
    name: APP_FRAG;

    node deps: [], restart: ::supervisor::policy::RestartPolicy::OnFailure,
        backoff: $crate::app::BACKOFF,
        watchdog: $crate::app::WATCHDOG observe,
        ctx: $crate::app::AppCtx,
        task: $crate::app::run;
}
