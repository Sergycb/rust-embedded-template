//! Kani-харнессы формальной верификации. Компилируются только под `cargo kani`
//! (см. CI-job `kani`); при обычной сборке модуль отсутствует полностью,
//! на `cargo build`/`cargo test`/clippy не влияет.
//!
//! Это заготовка, демонстрирующая конвенцию `#[kani::proof]` над чистой
//! no_std-логикой (парсеры, конечные автоматы, битовые операции) — Kani
//! таргетит только x86_64-хост, а не архитектуру MCU, поэтому не годится для
//! кода, трогающего периферию/MMIO. Замените/дополните реальными
//! инвариантами domain-логики по мере её появления.

fn saturating_add_u8(a: u8, b: u8) -> u8 {
    a.saturating_add(b)
}

#[kani::proof]
fn saturating_add_is_monotonic() {
    let a: u8 = kani::any();
    let b: u8 = kani::any();

    assert!(saturating_add_u8(a, b) >= a);
}
