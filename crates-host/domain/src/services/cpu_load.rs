//! Загрузка процессора, посчитанная по двум счётчикам.
//!
//! Считать «сколько времени занято» на МК нечем: там нет ни счётчика
//! инструкций, ни `/proc`, ни окна, в котором можно было бы посмотреть.
//! Остаётся единственное, что исполнителю доступно всегда, —
//! `Instant`: сколько тиков прошло и сколько из них микроконтроллер стоял
//! в `WFE`. Всё остальное время — работа, и разница между этими двумя
//! числами и есть загрузка.
//!
//! Считает [`CpuLoad`], узел [`crate::tasks::cpu_load`] этим пользуется —
//! а здесь только арифметика, без времени, железа и каналов, потому что
//! только её и можно проверить на хосте: подобрать граничные пары чисел в
//! тесте несравнимо дешевле, чем воспроизводить их на плате.

/// Снимок обоих счётчиков в один момент времени.
///
/// Разность между двумя снимками, а не сами значения: счётчик общего времени
/// начинается с нуля при старте, а счётчик сна живёт столько, сколько живёт
/// плата, — сравнивать их напрямую нельзя, можно только прирост.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Sample {
    /// Все тики с момента старта — `embassy_time::Instant::as_ticks`.
    pub total_ticks: u64,

    /// Сколько из них исполнитель проспал. Счётчик ведёт цикл в
    /// `crates-cross/app/src/main.rs`, а его тип объявлен здесь
    /// ([`crate::tasks::cpu_load::SleepTicks`]).
    pub sleep_ticks: u64,
}

/// Держатель предыдущего снимка: без него нечем посчитать прирост.
///
/// Состояние намеренно в вызывающем коде, а не в `static`: узлов такой
/// может быть сколько угодно, и каждый держит свой.
#[derive(Debug, Default)]
pub struct CpuLoad {
    previous: Option<Sample>,
}

impl CpuLoad {
    /// Пустой счётчик — первый снимок с него только запоминается.
    pub const fn new() -> Self {
        Self { previous: None }
    }

    /// Запомнить снимок и вернуть загрузку в процентах с прошлого, либо
    /// `None`, если прошлого снимка ещё не было.
    ///
    /// Первый снимок всегда `None` из принципа: с чем его сравнивать, тот
    /// прирост, что прошёл от старта, — это время инициализации, а не
    /// загрузка. Публиковать ноль там, где значения ещё нет, — значит врать.
    pub fn sample(&mut self, sample: Sample) -> Option<u8> {
        let previous = self.previous.replace(sample)?;
        // Насыщающие вычитания — не паранойя, а формат счётчиков: оба
        // могут перемотаться (u64 тиков это сотни лет, но «сотни лет» здесь
        // значит «перемотается на стендовом прогоне с вывернутым временем»),
        // и молчаливое переполнение отдало бы процент, посчитанный от
        // мусора.
        let total = sample.total_ticks.saturating_sub(previous.total_ticks);
        let sleep = sample.sleep_ticks.saturating_sub(previous.sleep_ticks);
        if total == 0 {
            // Два снимка подряд с одним и тем же общим временем: интервал
            // выродился в ноль, делить не на что. Ноль — честное «загрузки
            // не было» ровно настолько же, насколько честно «прошло ноль
            // времени».
            return Some(0);
        }
        // Счётчик сна не должен обгонять общий: он накапливает ровно те же
        // промежутки, что и общий. Но узел читает их не одним чтением (счётчик
        // сна — атомик, снятый на прошлом шаге цикла), поэтому «не должен»
        // держится здесь на saturating-вычитании, а не на обещании.
        let busy = total.saturating_sub(sleep);
        // Умножение на 100 переполнить не может: `busy` — доля прироста за
        // интервал съёма, а переполнение потребовало бы интервала порядка
        // 1.8e17 тиков, тогда как узел снимает счётчики раз в полсекунды.
        Some(((busy * 100) / total).min(100) as u8)
    }
}

#[cfg(test)]
mod tests {
    use super::{CpuLoad, Sample};

    fn sample(total_ticks: u64, sleep_ticks: u64) -> Sample {
        Sample {
            total_ticks,
            sleep_ticks,
        }
    }

    /// Первый снимок не с чем сравнивать — и «ноль» здесь был бы ложью:
    /// прирост от старта до первого съёма это время инициализации, а не
    /// загрузка.
    #[test]
    fn the_first_sample_has_nothing_to_compare_against() {
        let mut load = CpuLoad::new();
        assert_eq!(load.sample(sample(1_000, 0)), None);
    }

    /// Доля считается от ПРИРОСТА счётчиков, а не от их значений: счётчик
    /// сна живёт дольше общего (тот обнуляется при старте), и сравнение
    /// напрямую дало бы мусор.
    #[test]
    fn the_figure_comes_from_the_growth_not_from_the_values() {
        let mut load = CpuLoad::new();
        assert_eq!(load.sample(sample(10_000_000, 9_000_000)), None);
        // За интервал прошло 500 000 тиков, из них проспали 250 000.
        assert_eq!(load.sample(sample(10_500_000, 9_250_000)), Some(50));
    }

    /// Крайние случаи округления: целые проценты, полностью занятый и
    /// полностью свободный цикл.
    #[test]
    fn spans_from_idle_to_busy() {
        let mut load = CpuLoad::new();
        load.sample(sample(0, 0));
        assert_eq!(load.sample(sample(1_000, 1_000)), Some(0));
        assert_eq!(load.sample(sample(2_000, 1_000)), Some(100));
        assert_eq!(load.sample(sample(3_000, 1_999)), Some(0));
        // 999 занятых из 1000 — это 99, а не 100: округление вниз намеренное.
        assert_eq!(load.sample(sample(4_000, 2_000)), Some(99));
    }

    /// Неполный процент округляется вниз: 0.2% занятости — это 0, а не 1.
    #[test]
    fn a_fraction_of_a_percent_rounds_down() {
        let mut load = CpuLoad::new();
        load.sample(sample(0, 0));
        assert_eq!(load.sample(sample(10_000, 9_998)), Some(0));
        assert_eq!(load.sample(sample(20_000, 19_990)), Some(0));
    }

    /// Интервал выродился в ноль (два съёма в один тик) — делить не на что.
    #[test]
    fn a_zero_interval_reports_zero() {
        let mut load = CpuLoad::new();
        load.sample(sample(1_000, 100));
        assert_eq!(load.sample(sample(1_000, 100)), Some(0));
    }

    /// Счётчик сна не должен обгонять общий, но узел читает их не одним
    /// чтением. Обгон должен дать «спит», а не «-N%»: переноса в u64 здесь
    /// не происходит, потому что вычитание насыщающее.
    #[test]
    fn a_sleep_counter_ahead_of_the_clock_reads_as_idle() {
        let mut load = CpuLoad::new();
        load.sample(sample(1_000, 100));
        assert_eq!(load.sample(sample(2_000, 5_000)), Some(0));
    }

    /// Счётчик, ушедший назад (или перемотанный), не должен ронять вычитание
    /// в минус: из мусора вышел бы процент в сотни миллионов.
    #[test]
    fn a_counter_that_went_backwards_saturates_instead_of_wrapping() {
        let mut load = CpuLoad::new();
        // Общее время ушло назад — прирост выродился в ноль.
        load.sample(sample(u64::MAX - 500, 0));
        assert_eq!(load.sample(sample(400, 0)), Some(0));
        // Ушёл назад счётчик сна: всё, что осталось в приросте общего,
        // считается работой, а не отрицательным сном.
        load.sample(sample(0, u64::MAX));
        assert_eq!(load.sample(sample(1_000, 0)), Some(100));
    }
}
