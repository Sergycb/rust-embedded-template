//! Порты обновления прошивки и ошибки его применения.
//!
//! [`FirmwareUpdate`] — то, что нужно приёму и применению образа без подписи;
//! [`SignedFirmwareUpdate`] — то же плюс проверка подписи. Реализует их
//! `adapters::ota` (`Updater` и `Signed`), пользуются — `domain::download`,
//! `domain::update` и узел `domain::ota`.

/// Обновление прошивки: то, что нужно логике приёма и применения образа.
pub trait FirmwareUpdate {
    /// Отказ флеша или состояние, в котором операция запрещена (например,
    /// запись в раздел обновления до того, как подтверждён текущий образ).
    type Error;

    /// Кратность, которой обязана быть длина каждого [`write`](Self::write).
    ///
    /// У флеша это размер слова программирования — от четырёх байт до
    /// тридцати двух в зависимости от чипа. Канал доставки об этом не знает и
    /// отдаёт пакеты какой угодно длины, поэтому кто-то должен копить их до
    /// кратности; `domain::download::receive` делает это за вас.
    fn write_granularity(&mut self) -> u32;

    /// Самый длинный образ, который устройство способно принять и запустить.
    ///
    /// Нужна до начала приёма: длину образа сообщает недоверенный канал, и
    /// сверить её стоит раньше, чем начинать стирать флеш и принимать пакеты.
    ///
    /// Это не обязательно размер раздела, куда образ пишется: у схемы с
    /// обменом разделов приёмник по построению больше активного, и образ,
    /// влезший в приёмник, может не поместиться туда, где ему предстоит
    /// исполняться. Порт обещает меньшую из величин.
    fn capacity(&mut self) -> Result<u32, Self::Error>;

    /// В разделе обновления лежит образ, который терять нельзя.
    ///
    /// Два случая, и оба — «трогать раздел нельзя»: обновление помечено к
    /// обмену (bootloader перенесёт образ на ближайшем сбросе) и обмен уже
    /// случился, но новый образ себя не подтвердил (в разделе теперь
    /// предыдущая, заведомо рабочая прошивка — её bootloader и вернёт).
    /// Реализация обязана отказывать в [`prepare`](Self::prepare) и
    /// [`write`](Self::write), пока это так; логика применения обновления
    /// спрашивает отдельно, чтобы отличить этот отказ от отката по версии.
    fn is_busy(&mut self) -> Result<bool, Self::Error>;

    /// Готовит раздел обновления к приёму образа длиной `len` — стирает под
    /// него место.
    ///
    /// Стирается не весь раздел, а столько страниц, сколько нужно образу: на
    /// типичном «образ занимает половину раздела» это вдвое меньше времени
    /// (см. предупреждение ниже) и заметно меньше износ флеша. Длину знать
    /// обязательно; если ваш канал её не сообщает, передайте
    /// [`capacity`](Self::capacity) — подготовится место под самый большой
    /// образ, какой устройство вообще примет.
    ///
    /// Нулевая длина и длина сверх [`capacity`](Self::capacity) — ошибка, а не
    /// молчаливое «сколько влезет»: узнать о негодной длине нужно ДО стирания,
    /// потому что стирание уничтожает образ, в который устройство откатывается.
    ///
    /// Зовётся один раз перед первым [`write`](Self::write), а не при каждом
    /// куске: после подготовки запись любого куска в любом порядке кладёт байты
    /// ровно туда, куда просили. Без явной подготовки эту работу пришлось бы
    /// делать записи, а она видит только свой кусок и не знает, начало это
    /// передачи или её продолжение — «стирать сектор, если он новый» затирает
    /// уже принятое, стоит передаче начаться заново или прийти второму куску
    /// того же сектора.
    ///
    /// # Это самый долгий вызов во всём обновлении
    ///
    /// Стирание занимает от сотен миллисекунд (страницы по паре килобайт) до
    /// нескольких секунд (сектор в четверть мегабайта). Вызов синхронный и
    /// идёт из async-задачи (узел `domain::ota`, из `download::receive`), а
    /// драйверы флеша стирают внутри критической секции — на всё это время
    /// встают все задачи исполнителя, включая тикер графа, который кормит
    /// аппаратный сторож. Отсюда граница, которую компилятор не проверит:
    /// число секторов, накрываемых образом, умноженное на максимальное время
    /// стирания сектора из datasheet, обязано быть меньше аппаратного таймаута
    /// (`bsp::wdg::HW_TIMEOUT_US`) минус период тикера — иначе аппаратный
    /// сброс посреди подготовки, и `watchdog:` узлов тут ни при чём:
    /// срабатывает железо, а не наблюдатель. Стирание дольше таймаута
    /// наблюдаемого узла (`APP_WATCHDOG`) сбросом не грозит, но даёт ложное
    /// «узел перестал отмечаться» в логе. Задачи, которым нужен отклик, на
    /// это время замирают.
    fn prepare(&mut self, len: u32) -> Result<(), Self::Error>;

    /// Пишет кусок нового образа по смещению от начала раздела обновления.
    ///
    /// Требует, чтобы раздел был подготовлен [`prepare`](Self::prepare).
    /// Что будет иначе, зависит от чипа: большинство семейств отвечают ошибкой
    /// программирования, а F2/F4/F7 принимают запись **молча**, оставляя в
    /// ячейке побитовое И нового значения со старым. Полагаться ни на первое,
    /// ни на второе нельзя — стирайте явно.
    ///
    /// Смещение `u32`, как и у чтения ниже. У `embassy-boot` эти две функции
    /// разошлись (`usize` против `u32`), и на 32-битной цели разница не видна
    /// — зато видна у фейка, скомпилированного под хост, где `usize` вдвое
    /// шире: одно и то же смещение перестало бы выражаться обоими типами.
    fn write(&mut self, offset: u32, data: &[u8]) -> Result<(), Self::Error>;

    /// Читает записанное обратно — проверить принятое, не полагаясь на то, что
    /// запись прошла успешно. Разрешено и когда раздел занят: чтение ничего
    /// не портит.
    fn read(&mut self, offset: u32, buf: &mut [u8]) -> Result<(), Self::Error>;

    /// Подтверждает работоспособность текущего образа и отменяет откат.
    ///
    /// Без этого вызова обновление живёт ровно один запуск: следующий сброс
    /// вернёт предыдущий образ.
    fn mark_booted(&mut self) -> Result<(), Self::Error>;

    /// Просит bootloader поменять разделы местами на следующем сбросе. Сам
    /// сброс — за вызывающим: только он знает, когда устройство можно
    /// перезапустить.
    ///
    /// Проверок здесь нет намеренно — это путь без подписи: выход за границу
    /// раздела ловит сама запись, а версию в неподписанном образе правит кто
    /// угодно, и сравнивать её значило бы создавать видимость защиты. С
    /// подписью зовите `domain::update::apply_signed`, а не этот метод: в
    /// проекте с подписью адаптер (`adapters::ota::Signed`) на этот вызов
    /// отвечает отказом (`BadState`) — обмен там делает только
    /// `domain::update::apply_signed`.
    fn mark_updated(&mut self) -> Result<(), Self::Error>;
}

/// Обновление с проверкой подписи: то, что нужно `domain::update::apply_signed`.
///
/// Версия и ключ — свойства устройства, а не образа, и приходят через порт, а
/// не аргументами: так `app` не тянет константы из `bsp` мимо `Board`, а
/// host-тест логики подставляет любую пару.
pub trait SignedFirmwareUpdate: FirmwareUpdate {
    /// Версия прошивки, которая сейчас исполняется, в упакованном виде
    /// (`domain::firmware::pack`).
    fn running_version(&self) -> u32;

    /// Открытый ключ, которому устройство доверяет. Нули — «ключ не
    /// подставлен»; логика отказывает до криптографии, и убирать эту проверку
    /// нельзя: нулевой ключ ed25519 — точка малого порядка, подпись для такой
    /// подделывается за считанные попытки.
    fn public_key(&self) -> &[u8; 32];

    /// Проверяет подпись SHA-512 первых `len` байт раздела обновления по
    /// хранимому ключу и, если она верна, помечает обмен разделов.
    ///
    /// Только криптография и пометка: длину, занятость раздела и версию
    /// проверяет логика ДО этого вызова, в том порядке, в каком отказы
    /// различимы (`domain::update`). Неверная подпись — своим вариантом
    /// [`VerifyError::BadSignature`], а не как отказ флеша.
    fn verify_and_mark_updated(
        &mut self,
        signature: &[u8; 64],
        len: u32,
    ) -> Result<(), VerifyError<Self::Error>>;
}

/// Чем может закончиться проверка подписи в адаптере
/// ([`SignedFirmwareUpdate::verify_and_mark_updated`]).
///
/// Два варианта, а не один `Self::Error`: «подпись не сошлась» — отказ
/// образу, «флеш отказал» — отказ устройства, и отправителю образа нужно
/// разное — сменить ключ или прекратить попытки. Пока оба приходили одним
/// вариантом, узел OTA не мог сказать отправителю ничего точнее «не вышло».
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub enum VerifyError<E> {
    /// Подпись не сошлась с ключом устройства — или ключ не разбирается.
    #[error("подпись не сошлась")]
    BadSignature,
    /// Отказ флеша при чтении раздела или пометке обмена.
    #[error("отказ адаптера обновления: {0:?}")]
    Flash(E),
}

/// Чем может закончиться применение подписанного обновления
/// (`domain::update::apply_signed`).
///
/// Каждому отказу — свой вариант, и это не для красоты: пока «длина больше
/// раздела» и «ключ не подставлен» возвращали одно и то же, target-тест
/// оставался зелёным после удаления одной из защит (проверено удалением на
/// живой плате). Человеку, разбирающему лог с устройства, разница между
/// «подпись не сошлась» и «прислали старую прошивку» важнее всего остального.
#[derive(Debug, PartialEq, Eq, thiserror::Error)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub enum UpdateError<E> {
    /// Длина из недоверенного канала больше вместимости. Проверяется ПЕРВОЙ:
    /// `verify_and_mark_updated` в embassy-boot начинается с
    /// `assert!(update_len <= dfu.capacity())`, то есть с паники, а в release
    /// паника это сброс — одно кривое число уводило бы устройство в цикл.
    #[error("образ длиной {len} байт не помещается в раздел вместимостью {capacity} байт")]
    TooLong { len: u32, capacity: u32 },
    /// Образ короче собственного хвоста с версией — мусор в канале, а не откат.
    #[error("длина образа {len} меньше хвоста с версией")]
    Truncated { len: u32 },
    /// В разделе обновления лежит образ отката — трогать его нельзя. Отделён от
    /// [`Rollback`](Self::Rollback): версия у того образа заведомо старее, и
    /// проверка версии честно ответила бы «откат», соврав о причине.
    #[error("раздел обновления занят образом, в который устройство откатывается")]
    Busy,
    /// Образ не новее текущего — попытка отката. Обе версии в упакованном
    /// виде, разобрать их обратно умеет `domain::firmware::unpack`.
    #[error("отклонён откат: текущая версия {current}, предложенная {incoming}")]
    Rollback { current: u32, incoming: u32 },
    /// Открытый ключ не подставлен (нули) — отказ до криптографии, см.
    /// [`SignedFirmwareUpdate::public_key`].
    #[error("открытый ключ не подставлен")]
    NoPublicKey,
    /// Подпись не сошлась — отдельно от [`Flash`](Self::Flash): узел OTA
    /// сообщает отправителю код `Signature`, а не `Device`.
    #[error("подпись не сошлась")]
    BadSignature,
    /// Всё, что приходит из адаптера: отказ флеша, негодное состояние.
    #[error("отказ адаптера обновления: {0:?}")]
    Flash(E),
}

impl<E> From<E> for UpdateError<E> {
    fn from(error: E) -> Self {
        Self::Flash(error)
    }
}
