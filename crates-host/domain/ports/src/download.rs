//! Порт канала доставки образа и ошибка его приёма.
//!
//! [`ImageSource`] реализует проект под свой транспорт (USB CDC, UART, сеть,
//! SD-карта) — в `crates-cross/bsp`, там, где живёт периферия. Пользуется им
//! `domain::download::receive` и узел `domain::ota`.

/// Заголовок образа, который канал получил от отправителя, — то, что нужно
/// знать до первого куска.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub struct Announce {
    /// Длина образа в байтах. Сверяется с вместимостью ДО стирания раздела.
    pub len: u32,
    /// Подпись образа, если канал её передаёт. `None` в проекте с подписью —
    /// отказ до стирания (`Rejection::Signature`); проект без подписи поле
    /// не читает.
    pub signature: Option<[u8; 64]>,
}

/// Код отказа для отправителя образа.
///
/// Плоский и `Copy` намеренно: [`ImageSource`] не знает тип ошибки флеша, а
/// отправителю нужен код, на который он может отреагировать — исправить
/// длину, дождаться перезагрузки, сменить ключ, — а не payload. Полная
/// ошибка уходит в лог узла `domain::ota`.
#[non_exhaustive]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub enum Rejection {
    /// Заявленная длина негодная: ноль, больше раздела, короче хвоста с
    /// версией.
    Length,
    /// Передача не сошлась с заголовком: байт больше или меньше обещанного.
    Transfer,
    /// В разделе образ, который терять нельзя (обмен ждёт сброса или ещё не
    /// подтверждён) — сначала перезагрузка.
    Busy,
    /// Версия образа не новее текущей.
    Rollback,
    /// Подписи нет, ключ не подставлен или подпись не сошлась.
    Signature,
    /// Отказ флеша или адаптера на стороне устройства.
    Device,
}

/// Канал доставки образа: USB CDC, UART-протокол, сеть, SD-карта — у каждой
/// платы свой, шаблон его не выбирает. Узел `domain::ota` ждёт от него три
/// вещи: заголовок, куски и способ сообщить исход отправителю.
///
/// Порт — весь протокол обновления с точки зрения устройства, а формат
/// пакетов и проверка целостности — за реализацией: узел про них не знает.
///
/// Порядок вызовов в одном цикле узла — `begin`, затем ноль или больше
/// `next`, затем `finish`, — и три следствия для реализации:
///
/// * `next` до `begin` не зовётся никогда;
/// * `finish` может прийти без единого `next` — отказ по заголовку, до
///   чтения образа (`Busy`, `Length` по заявленной длине, `Signature` без
///   подписи в заголовке, `Device` на стирании) — или посреди потока, когда
///   узел перестал читать (`Transfer` при лишних данных, `Device` на записи);
/// * после `finish` узел сразу зовёт `begin`, и остаток прерванной передачи
///   транспорт обязан сбросить сам — иначе следующий `begin` разберёт хвост
///   старого образа как заголовок.
///
/// Для request/response-протокола это и определяет, что делать в `finish`:
/// NACK на заголовок, если кусков не было, против NACK после приёма с
/// вычиткой хвоста.
pub trait ImageSource {
    /// Отказ канала: обрыв связи, таймаут, ошибка протокола. Узел на него
    /// выходит `TaskExit::Failed` — граф перезапустит его с backoff'ом.
    type Error;

    /// Ждёт заголовок следующего образа — сколько угодно долго.
    ///
    /// Узел зовёт это в начале каждого цикла и висит здесь всё время, пока
    /// обновления нет; прогресса, о котором можно отметиться у сторожа, в
    /// этом ожидании нет — поэтому у узла OTA нет `watchdog:` (см. doc у
    /// `domain::ota::run`).
    async fn begin(&mut self) -> Result<Announce, Self::Error>;

    /// Следующий кусок образа — любой длины, хоть в один байт; `None` —
    /// передача окончена.
    ///
    /// Срез заимствован у источника: буфер принадлежит каналу (DMA-буфер,
    /// пакет протокола), и копировать его ради интерфейса незачем — целые
    /// слова уходят во флеш прямо отсюда.
    async fn next(&mut self) -> Result<Option<&[u8]>, Self::Error>;

    /// Исход цикла: `Ok(())` — образ принят и помечен к обмену на следующем
    /// сбросе, `Err(_)` — отвергнут, с кодом для отправителя.
    ///
    /// Что с этим делать — ответить хосту, сбросить МК
    /// (`cortex_m::peripheral::SCB::sys_reset()`), и то и другое — решает
    /// реализация: только она знает, когда устройство можно перезапускать.
    /// Вернулось `Ok(())` — узел ждёт следующий `begin`, а значит, недочитанный
    /// хвост прерванной передачи надо сбросить здесь (см. doc трейта).
    async fn finish(&mut self, outcome: Result<(), Rejection>) -> Result<(), Self::Error>;
}

/// Что может пойти не так при приёме образа (`domain::download::receive`).
///
/// Два параметра — два порта: отказ канала и отказ флеша приходят разными
/// вариантами, и `From` для них нет намеренно — при одинаковых типах ошибок
/// два impl'а конфликтовали бы, а какой из портов отказал, важнее любого
/// удобства.
#[derive(Debug, PartialEq, Eq, thiserror::Error)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub enum DownloadError<S, F> {
    /// Обещали образ нулевой длины. Проверяется здесь, а не оставляется
    /// реализации порта: `prepare(0)` не стёр бы ничего, и первая же запись
    /// легла бы в нестёртую память, на F2/F4/F7 молча.
    #[error("заявлена нулевая длина образа")]
    Empty,
    /// Устройство столько не примет: образ длиннее того, что помещается в
    /// раздел. Проверяется до стирания — раздел остаётся нетронутым.
    #[error("образ длиной {announced} байт не помещается в раздел вместимостью {capacity} байт")]
    TooLong { announced: u32, capacity: u32 },
    /// Порт назвал гранулярность записи, с которой работать нельзя: ноль
    /// (деление на него паникует, а паника в release — это сброс) или больше
    /// самого широкого слова STM32 (32 байта), то есть шире буфера.
    #[error("порт вернул негодную гранулярность записи: {0} байт")]
    UnusableGranularity(u32),
    /// Прислали больше, чем обещали в начале. Приём прекращается: это либо
    /// сбой канала, либо попытка вылезти за раздел.
    #[error("получено {received} байт при заявленных {announced}")]
    TooMuchData { announced: u32, received: u32 },
    /// Передача кончилась, не добрав до обещанной длины.
    #[error("приём прерван: получено {received} из {announced} байт")]
    Incomplete { announced: u32, received: u32 },
    /// Отказ канала доставки. `{0:?}`, а не `{0}`: порт не обещает `Display`.
    #[error("отказ канала: {0:?}")]
    Source(S),
    /// Отказ самого флеша — по той же причине через `Debug`.
    #[error("отказ флеша: {0:?}")]
    Flash(F),
}
