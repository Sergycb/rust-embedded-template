//! Слово записи флеша — общий предел для OTA и хранилища узла CANopen.

/// Самое широкое слово записи среди STM32 — тридцать два байта (H7).
///
/// Буфер под слово держится на этот максимум, а флешу отдаётся срез нужной
/// длины: так адаптер обновления (`embassy-boot` требует буфер ровно в
/// `STATE::WRITE_SIZE` байт с выравниванием флеша), решение bootloader'а и
/// хранилище узла CANopen (элемент `sequential-storage` дополняется до слова)
/// остаются generic и не знают слова конкретного чипа.
pub const MAX_WRITE_SIZE: usize = 32;
