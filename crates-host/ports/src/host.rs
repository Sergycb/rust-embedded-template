//! Порт обработчика сообщений хоста.
//!
//! Реализует приложение — оно знает схему и свои задачи; пользуется им узел
//! `domain::host` (HOST), который принимает кадры, разбирает и кодирует
//! сообщения и про схему не знает.

/// Обработчик сообщений хоста: единственное место, где сообщения схемы
/// превращаются в типы приложения.
///
/// В задачи уходят уже проверенные значения своих типов, а не
/// сгенерированные: в protobuf нет newtype и диапазонов, и то, что значение
/// разобралось, не значит, что оно допустимо. Недопустимое отсекается здесь,
/// ответом-ошибкой, и до задач не доходит.
pub trait HostService {
    /// Сообщение запроса — тип, сгенерированный из схемы.
    type Request;
    /// Сообщение ответа — тип, сгенерированный из схемы.
    type Response;

    /// Выполняет запрос и строит ответ: проверяет значения, переводит их в
    /// свои типы, отдаёт задачам, ждёт исход.
    ///
    /// `request_id` из запроса — если он есть в схеме — ответ обязан
    /// вернуть как есть: по нему хост сопоставляет ответ с запросом.
    async fn handle(&mut self, request: Self::Request) -> Self::Response;

    /// Ответ на кадр, который не разобрался как запрос: битые байты, строка
    /// длиннее ёмкости, чужое сообщение. `request_id` взять неоткуда — обычно
    /// 0.
    fn malformed(&mut self) -> Self::Response;
}
