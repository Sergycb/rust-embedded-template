//! Ключ хоста SSH — зерно ed25519, 32 байта.
//!
//! Трейт, потому что у узла `domain::ssh` реализаций две, по одной на вариант
//! генерации: ключ, вшитый в прошивку (`domain::ssh::Fixed`), и созданный
//! платой при первом старте и хранимый в разделе настроек
//! (`domain::ssh::Stored`). Без трейта узлу пришлось бы различать их Liquid'ом
//! в коде логики.

/// Откуда узел SSH берёт ключ хоста.
pub trait HostKey {
    /// Зерно ключа хоста. Не отказывает: ключ нужен, чтобы вообще пустить
    /// клиента, и реализация, которой не удалось сохранить ключ, отдаёт его
    /// хотя бы на этот запуск.
    async fn seed(&mut self) -> [u8; 32];
}
