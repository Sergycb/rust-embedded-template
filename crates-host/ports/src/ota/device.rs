//! Всё, что узлу OTA нужно от платы, одним объектом.

use super::download::ImageSource;
use super::update::FirmwareUpdate;

/// OTA платы: канал доставки образа и запись во флеш под одним владельцем.
///
/// Плата отдаёт приложению один объект, а не пару: узел `domain::ota` берёт его
/// одним входом и сам разбирает на половины, когда они ему нужны. Две ссылки
/// сразу (приём читает канал и пишет во флеш в одном вызове) — поэтому метод
/// один и возвращает обе, а не по методу на половину.
pub trait OtaDevice {
    /// Канал доставки образа.
    type Link: ImageSource;
    /// Запись образа во флеш.
    type Flash: FirmwareUpdate;

    /// Обе половины сразу.
    fn parts(&mut self) -> (&mut Self::Link, &mut Self::Flash);
}
