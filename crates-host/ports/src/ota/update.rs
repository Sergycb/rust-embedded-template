//! Порт обновления прошивки, запись о подписи для bootloader'а и ошибки
//! применения.
//!
//! [`FirmwareUpdate`](crate::FirmwareUpdate) — то, что нужно приёму и
//! применению образа, с подписью и без. Реализует его `adapters::ota::Updater`,
//! пользуются — `domain::ota::download`, `domain::ota::update` и узел
//! `domain::ota`. Методы, которые ходят во флеш, асинхронные: за портом может
//! стоять и внутренний флеш, и внешняя микросхема на SPI.
//!
//! [`PendingImage`](crate::PendingImage) — то, что приложение оставляет
//! bootloader'у о принятом подписанном образе; пишет его `domain::ota::update`,
//! читает `domain::ota::boot::screen_update` в bootloader'е. Формат здесь, потому
//! что обе стороны обязаны понимать его одинаково.
//!
//! [`layout_fingerprint`](crate::layout_fingerprint) — отпечаток раскладки
//! памяти, который `cargo xtask build` кладёт в хвост образа, а приложение
//! сверяет со своим на `Finish`. Формула здесь по той же причине: считают её
//! обе стороны.

/// Границы разделов из `memory.x`, по которым считается отпечаток раскладки,
/// — в этом порядке.
///
/// Только они: это ровно то, что обязаны одинаково понимать приложение и
/// bootloader (`embassy-boot` читает те же символы в обоих). Размеры страниц
/// не входят: они у пары и так общие (число из генерации в `[env]`), а
/// различие в них — не другая раскладка, а другой чип.
pub const LAYOUT_SYMBOLS: [&str; 6] = [
    "__bootloader_state_start",
    "__bootloader_state_end",
    "__bootloader_active_start",
    "__bootloader_active_end",
    "__bootloader_dfu_start",
    "__bootloader_dfu_end",
];

/// Самое широкое слово записи флеша среди STM32 — тридцать два байта (H7).
///
/// Буфер под слово держится на этот максимум, а флешу отдаётся срез нужной
/// длины: так адаптер обновления (`embassy-boot` требует буфер ровно в
/// `STATE::WRITE_SIZE` байт с выравниванием флеша), буферизация образа до
/// слова (`domain::ota::download`) и решение bootloader'а
/// (`domain::ota::boot`) остаются generic и не знают слова конкретного чипа.
pub const MAX_WRITE_SIZE: usize = 32;

/// Обновление прошивки: то, что нужно логике приёма и применения образа.
#[must_use]
pub trait FirmwareUpdate {
    /// Отказ флеша или состояние, в котором операция запрещена (например,
    /// запись в раздел обновления до того, как подтверждён текущий образ).
    type Error;

    /// Кратность, которой обязана быть длина каждого [`write`](Self::write).
    ///
    /// У флеша это размер слова программирования — от четырёх байт до
    /// тридцати двух в зависимости от чипа. Канал доставки об этом не знает и
    /// отдаёт пакеты какой угодно длины, поэтому кто-то должен копить их до
    /// кратности; `domain::ota::download::Transfer` делает это за вас.
    fn write_granularity(&mut self) -> u32;

    /// Самый длинный образ, который устройство способно принять и запустить.
    ///
    /// Нужна до начала приёма: длину образа сообщает недоверенный канал, и
    /// сверить её стоит раньше, чем начинать стирать флеш и принимать пакеты.
    ///
    /// Это не обязательно размер раздела, куда образ пишется: у схемы с
    /// обменом разделов приёмник по построению больше активного, и образ,
    /// влезший в приёмник, может не поместиться туда, где ему предстоит
    /// исполняться. Порт обещает меньшую из величин.
    ///
    /// # Errors
    ///
    /// Возвращает ошибку флеша, если чтение конфигурации раздела не удалось.
    fn capacity(&mut self) -> Result<u32, Self::Error>;

    /// Отпечаток раскладки памяти этой прошивки ([`layout_fingerprint`] по
    /// [`LAYOUT_SYMBOLS`]) — с ним сверяется отпечаток в хвосте принятого
    /// образа.
    ///
    /// Без значения по умолчанию намеренно: реализация, которая «принимает
    /// всё», пропустила бы образ под чужую раскладку к обмену, а такой образ
    /// не запустится (раздел `ACTIVE` у него в другом месте) или обмен
    /// испортит соседние разделы.
    fn layout(&self) -> u32;

    /// В разделе обновления лежит образ, который терять нельзя.
    ///
    /// Два случая, и оба — «трогать раздел нельзя»: обновление помечено к
    /// обмену (bootloader перенесёт образ на ближайшем сбросе) и обмен уже
    /// случился, но новый образ себя не подтвердил (в разделе теперь
    /// предыдущая, заведомо рабочая прошивка — её bootloader и вернёт).
    /// Реализация обязана отказывать в [`prepare`](Self::prepare) и
    /// [`write`](Self::write), пока это так; логика применения обновления
    /// спрашивает отдельно, чтобы отличить этот отказ от отката по версии.
    ///
    /// # Errors
    ///
    /// Возвращает ошибку флеша, если проверка состояния раздела не удалась.
    async fn is_busy(&mut self) -> Result<bool, Self::Error>;

    /// Готовит раздел обновления к приёму образа длиной `len` — стирает под
    /// него место.
    ///
    /// Стирается не весь раздел, а столько страниц, сколько нужно образу: на
    /// типичном «образ занимает половину раздела» это вдвое меньше времени
    /// (см. предупреждение ниже) и заметно меньше износ флеша. Длину знать
    /// обязательно; если ваш канал её не сообщает, передайте
    /// [`capacity`](Self::capacity) — подготовится место под самый большой
    /// образ, какой устройство вообще примет.
    ///
    /// Нулевая длина и длина сверх [`capacity`](Self::capacity) — ошибка, а не
    /// молчаливое «сколько влезет»: узнать о негодной длине нужно ДО стирания,
    /// потому что стирание уничтожает образ, в который устройство откатывается.
    ///
    /// Зовётся один раз перед первым [`write`](Self::write), а не при каждом
    /// куске: после подготовки запись любого куска в любом порядке кладёт байты
    /// ровно туда, куда просили. Без явной подготовки эту работу пришлось бы
    /// делать записи, а она видит только свой кусок и не знает, начало это
    /// передачи или её продолжение — «стирать сектор, если он новый» затирает
    /// уже принятое, стоит передаче начаться заново или прийти второму куску
    /// того же сектора.
    ///
    /// # Это самый долгий вызов во всём обновлении
    ///
    /// Стирание занимает от сотен миллисекунд (страницы по паре килобайт) до
    /// нескольких секунд (сектор в четверть мегабайта). Вызов асинхронный, но
    /// внутренний флеш стирается внутри критической секции драйвера — на всё
    /// это время встают все задачи исполнителя.
    // {%- if ota_store == "external" %}
    /// Внешняя флеш на SPI с DMA исполнитель не держит.
    // {%- endif %}
    // {%- if graph == "true" %}
    /// Встаёт и тикер графа, который кормит аппаратный сторож.
    /// Отсюда граница, которую компилятор не проверит: число секторов,
    /// накрываемых образом, умноженное на максимальное время стирания сектора
    /// из datasheet, обязано быть меньше аппаратного таймаута
    /// (`bsp::wdg::HW_TIMEOUT_US`) минус период тикера — иначе аппаратный сброс
    /// посреди подготовки, и `watchdog:` узлов тут ни при чём: срабатывает
    /// железо, а не наблюдатель. Стирание дольше таймаута наблюдаемого узла
    /// (`domain::heartbeat::WATCHDOG`) сбросом не грозит, но даёт ложное «узел
    /// перестал отмечаться» в логе.
    // {%- endif %}
    /// Задачи, которым нужен отклик, на это время замирают.
    ///
    /// # Errors
    ///
    /// Возвращает ошибку флеша, если стирание не удалось.
    async fn prepare(&mut self, len: u32) -> Result<(), Self::Error>;

    /// Пишет кусок нового образа по смещению от начала раздела обновления.
    ///
    /// Требует, чтобы раздел был подготовлен [`prepare`](Self::prepare).
    /// Что будет иначе, зависит от чипа: большинство семейств отвечают ошибкой
    /// программирования, а F2/F4/F7 принимают запись **молча**, оставляя в
    /// ячейке побитовое И нового значения со старым. Полагаться ни на первое,
    /// ни на второе нельзя — стирайте явно.
    ///
    /// Смещение `u32`, как и у чтения ниже. У `embassy-boot` эти две функции
    /// разошлись (`usize` против `u32`), и на 32-битной цели разница не видна
    /// — зато видна у фейка, скомпилированного под хост, где `usize` вдвое
    /// шире: одно и то же смещение перестало бы выражаться обоими типами.
    ///
    /// # Errors
    ///
    /// Возвращает ошибку флеша, если запись не удалась.
    async fn write(&mut self, offset: u32, data: &[u8]) -> Result<(), Self::Error>;

    /// Читает записанное обратно — проверить принятое, не полагаясь на то, что
    /// запись прошла успешно. Разрешено и когда раздел занят: чтение ничего
    /// не портит.
    ///
    /// # Errors
    ///
    /// Возвращает ошибку флеша, если чтение не удалось.
    async fn read(&mut self, offset: u32, buf: &mut [u8]) -> Result<(), Self::Error>;

    /// Подтверждает работоспособность текущего образа и отменяет откат.
    ///
    /// Без этого вызова обновление живёт ровно один запуск: следующий сброс
    /// вернёт предыдущий образ.
    ///
    /// # Errors
    ///
    /// Возвращает ошибку флеша, если пометка не удалась.
    async fn mark_booted(&mut self) -> Result<(), Self::Error>;

    /// Просит bootloader поменять разделы местами на следующем сбросе. Сам
    /// сброс — за вызывающим: только он знает, когда устройство можно
    /// перезапустить.
    ///
    /// Проверок здесь нет намеренно: выход за границу раздела ловит сама
    /// запись, а версию в неподписанном образе правит кто угодно, и сравнивать
    /// её значило бы создавать видимость защиты. С подписью зовите
    /// `domain::ota::update::apply_signed`: она оставит bootloader'у запись о
    /// подписи ([`PendingImage`]) и только потом позовёт
    /// этот метод — обмен без записи bootloader отвергнет.
    ///
    /// # Errors
    ///
    /// Возвращает ошибку флеша, если пометка не удалась.
    async fn mark_updated(&mut self) -> Result<(), Self::Error>;
}

/// Что приложение оставляет bootloader'у о принятом подписанном образе: длину
/// и подпись.
///
/// Лежит в запасной странице раздела обновления — по смещению
/// [`FirmwareUpdate::capacity`] (размер `ACTIVE`). `DFU` по построению на
/// страницу больше `ACTIVE` (`assert_partitions` в `embassy-boot`), и эта
/// страница нужна только самому обмену как черновик: до него она свободна, а
/// первый же шаг обмена её затирает — к этому моменту bootloader запись уже
/// проверил. Своё место в разделе, а не отдельная запись: подпись должна
/// пережить перезагрузку между приёмом и проверкой, а состояние bootloader'а
/// `embassy-boot` стирает сам.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub struct PendingImage {
    /// Длина образа в байтах — сколько начальных байт раздела покрывает
    /// подпись.
    pub len: u32,
    /// Подпись ed25519 над SHA-512 образа — так её ставит `cargo xtask build`.
    pub signature: [u8; 64],
}

impl PendingImage {
    /// Размер записи во флеше: магия (8), длина (4), резерв (4), подпись (64)
    /// — 80 байт, дополненные до 96: запись идёт одним куском, и на любом
    /// STM32 она обязана быть кратна слову (до 32 байт у H7).
    pub const LEN: usize = 96;

    /// Магия записи — отличает её от стёртой страницы и от остатков чужих
    /// данных.
    const MAGIC: [u8; 8] = *b"OTA-SIG1";

    /// Запись в том виде, в каком она ложится во флеш.
    #[must_use]
    pub fn to_bytes(self) -> [u8; Self::LEN] {
        let mut out = [0xFF; Self::LEN];
        out[..8].copy_from_slice(&Self::MAGIC);
        out[8..12].copy_from_slice(&self.len.to_le_bytes());
        out[16..80].copy_from_slice(&self.signature);
        out
    }

    /// Разбирает прочитанное из флеша; `None` — записи нет (нет магии).
    #[must_use]
    pub fn from_bytes(bytes: &[u8; Self::LEN]) -> Option<Self> {
        if bytes[..8] != Self::MAGIC {
            return None;
        }
        let mut len = [0; 4];
        len.copy_from_slice(&bytes[8..12]);
        let mut signature = [0; 64];
        signature.copy_from_slice(&bytes[16..80]);
        Some(Self {
            len: u32::from_le_bytes(len),
            signature,
        })
    }
}

// Запись идёт одним куском: её длина обязана быть кратна самому широкому слову.
const _: () = assert!(PendingImage::LEN.is_multiple_of(MAX_WRITE_SIZE));

/// Чем может закончиться применение подписанного обновления
/// (`domain::ota::update::apply_signed`).
///
/// Каждому отказу — свой вариант, и это не для красоты: пока разные защиты
/// возвращали одно и то же, target-тест оставался зелёным после удаления одной
/// из них (проверено удалением на живой плате). Отказов подписи здесь нет:
/// её проверяет bootloader, и о неудаче отправитель узнаёт по тому, что версия
/// после перезагрузки не сменилась.
#[derive(Debug, PartialEq, Eq, thiserror::Error)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
#[non_exhaustive]
pub enum UpdateError<E> {
    /// Длина из недоверенного канала больше вместимости. Проверяется ПЕРВОЙ:
    /// длина уходит в запись для bootloader'а, и образ, не помещающийся в
    /// `ACTIVE`, он отверг бы только после перезагрузки.
    #[error("образ длиной {len} байт не помещается в раздел вместимостью {capacity} байт")]
    TooLong { len: u32, capacity: u32 },
    /// Образ короче собственного хвоста (раскладка и версия) — мусор в канале,
    /// а не откат.
    #[error("длина образа {len} меньше хвоста с раскладкой и версией")]
    Truncated { len: u32 },
    /// В разделе обновления лежит образ отката — трогать его нельзя. Отделён от
    /// [`Rollback`](Self::Rollback): версия у того образа заведомо старее, и
    /// проверка версии честно ответила бы «откат», соврав о причине.
    #[error("раздел обновления занят образом, в который устройство откатывается")]
    Busy,
    /// Образ не новее текущего — попытка отката. Обе версии в упакованном
    /// виде (см. `domain::ota::version`).
    #[error("отклонён откат: текущая версия {current}, предложенная {incoming}")]
    Rollback { current: u32, incoming: u32 },
    /// Образ собран под другую раскладку памяти: отпечаток в его хвосте не
    /// совпал с отпечатком этой прошивки (см. [`layout_fingerprint`]). Обмен
    /// не запрашивается — такой образ после него не запустился бы.
    #[error(
        "образ собран под другую раскладку: у устройства {device:#010x}, у образа {image:#010x}"
    )]
    Layout { device: u32, image: u32 },
    /// Всё, что приходит из адаптера: отказ флеша, негодное состояние.
    #[error("отказ адаптера обновления: {0:?}")]
    Flash(E),
}

impl<E> From<E> for UpdateError<E> {
    fn from(error: E) -> Self {
        Self::Flash(error)
    }
}

/// Отпечаток раскладки: FNV-1a 32 над границами [`LAYOUT_SYMBOLS`], каждая
/// — `u32` little-endian.
///
/// Считают его `cargo xtask build` (значения символов в ELF) и прошивка
/// (адреса тех же символов в рантайме), поэтому формула одна и здесь. Хеш, а
/// не сами границы: в хвосте образа на них места нет, а защищается он не от
/// подделки (это дело подписи), а от образа, собранного под другую раскладку.
#[must_use]
pub const fn layout_fingerprint(bounds: [u32; 6]) -> u32 {
    /// Параметры FNV-1a 32: начальное значение и простое число.
    const OFFSET_BASIS: u32 = 0x811C_9DC5;
    const PRIME: u32 = 0x0100_0193;

    let mut hash = OFFSET_BASIS;
    let mut i = 0;
    while i < bounds.len() {
        let bytes = bounds[i].to_le_bytes();
        let mut j = 0;
        while j < bytes.len() {
            hash ^= bytes[j] as u32;
            hash = hash.wrapping_mul(PRIME);
            j += 1;
        }
        i += 1;
    }
    hash
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Вектор закреплён литералом: формулу считают и xtask, и прошивка, и
    /// молча поменять её значит отвергать все уже собранные образы.
    #[test]
    fn layout_fingerprint_is_pinned() {
        assert_eq!(layout_fingerprint([0; 6]), 0xE2BA_14A5);
        assert_eq!(
            layout_fingerprint([0x4000, 0x6000, 0x8000, 0x4_0000, 0x4_0000, 0x7_8000]),
            0xF953_808A
        );
    }

    /// Порядок границ входит в отпечаток: раскладка с переставленными
    /// разделами — другая раскладка.
    #[test]
    fn swapping_two_bounds_changes_the_fingerprint() {
        let bounds = [0x4000, 0x6000, 0x8000, 0x4_0000, 0x4_0000, 0x7_8000];
        let mut swapped = bounds;
        swapped.swap(2, 4);
        assert_ne!(layout_fingerprint(bounds), layout_fingerprint(swapped));
    }

    #[test]
    fn pending_image_round_trips() {
        let image = PendingImage {
            len: 0x0001_2345,
            signature: [0xA5; 64],
        };
        let bytes = image.to_bytes();
        assert_eq!(bytes.len(), PendingImage::LEN);
        assert_eq!(PendingImage::from_bytes(&bytes), Some(image));
    }

    #[test]
    fn foreign_magic_and_erased_flash_are_not_a_record() {
        let mut bytes = PendingImage {
            len: 1,
            signature: [7; 64],
        }
        .to_bytes();
        bytes[0] ^= 1;
        assert_eq!(PendingImage::from_bytes(&bytes), None, "чужая магия");
        assert_eq!(
            PendingImage::from_bytes(&[0xFF; PendingImage::LEN]),
            None,
            "стёртая страница"
        );
    }
}
