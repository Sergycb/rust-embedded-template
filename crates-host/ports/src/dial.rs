//! Порт исходящего соединения: клиент сам подключается к серверу.
//!
//! Реализует его `adapters::net::TcpClient` над сокетом `embassy-net`.
//! Пользуется им клиент MQTT в `domain`: подключиться к брокеру, провести
//! сессию по потоку байтов соединения, положить трубку.

use core::net::SocketAddrV4;

/// Исходящее соединение: одна попытка подключиться на вызов.
///
/// Поток байтов в порт не входит: потребитель берёт
/// `D: Dial + embedded_io_async::Read + embedded_io_async::Write` и читает и
/// пишет соединение, которое открыл [`dial`](Dial::dial).
///
/// Отказ — неудачная попытка ([`dial`](Dial::dial) возвращает ошибку) и
/// соединение, которое сервер оборвал сразу (неверный пароль). После отказа
/// и после любой ошибки сессии узел пишет в лог, кладёт трубку и сразу зовёт
/// `dial` снова, а переждать отказ — дело реализации, на следующем вызове:
/// пауза перед попыткой растёт с числом отказов подряд. Реализация, которая
/// возвращает ошибку снова без ожидания, крутила бы узел, не отдавая
/// исполнитель, и засыпала бы сервер попытками.
#[must_use]
pub trait Dial {
    /// Почему попытка не удалась.
    type Error;

    /// Выдерживает паузу по числу отказов подряд и один раз пытается
    /// подключиться к `to`.
    ///
    /// Прежнее соединение, если трубку не положили, закрывается.
    ///
    /// # Errors
    ///
    /// Подключиться не удалось: сервер не отвечает, отверг соединение или
    /// до него нет маршрута.
    async fn dial(&mut self, to: SocketAddrV4) -> Result<(), Self::Error>;

    /// Закрывает текущее соединение (сбросом, без обмена остатком данных);
    /// следующий [`dial`](Dial::dial) откроет новое.
    fn hang_up(&mut self);
}
