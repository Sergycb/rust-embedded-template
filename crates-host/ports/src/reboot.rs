//! Порт перезагрузки МК.

/// Перезагрузка МК.
///
/// Ею узел OTA выполняет команду `Reboot` (`domain::ota::Command`), а
/// release-паникёр заканчивает панику: причину он уже записал в регион
/// `PANIC`, и без сброса следующий запуск её не прочитает.
///
/// Порт, а не прямой сброс в `domain`: сбросить ядро умеет только чип
/// (`cpu::System`, `crates-cross/cpu/src/system.rs`), а на хосте узел
/// проверяется с фейком. `domain` видит только порт.
pub trait Reboot {
    /// Сбрасывает МК; не возвращается.
    fn reboot(&mut self) -> !;
}
