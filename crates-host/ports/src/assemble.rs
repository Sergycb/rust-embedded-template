//! Как адаптер собирается из рычага платы и памяти приложения.

/// Адаптер, который собирается из рычага платы (`Source`: поле `Board` —
/// поток байтов, кусок флеша и т. п.) и памяти приложения (`Buffers`: ссылки на
/// его статики — буферы, а с ними и то, что задаёт протокол, например порт).
///
/// Нужен, чтобы адаптер собирал узел `domain`, а не приложение: узел обобщён
/// по типу адаптера и зовёт `L::assemble(source, buffers)`, зная только этот
/// трейт; приложение называет тип
// {%- if graph == "true" %}
/// (параметром фрагмента графа)
// {%- endif %}
/// и раздаёт поля
/// платы и ссылки на свои статики, но объектов не строит. Какой адаптер под
/// каким рычагом — решает генерация, выбирая тип.
pub trait Assemble: Sized {
    /// Рычаг платы, над которым собирается адаптер.
    type Source;
    /// Память и параметры от приложения: ссылки на его статики.
    type Buffers;

    /// Собирает адаптер над `source` в памяти `buffers`.
    fn assemble(source: Self::Source, buffers: Self::Buffers) -> Self;
}
