//! Порт хранилища настроек.
//!
//! Реализует `adapters::settings::Settings`, отдаёт полем `Board::config`
//! проект с разделом `CONFIG`; формат значений выбирает проект.

/// Настройки, переживающие перезапуск и обновление прошивки.
///
/// Ключ числовой: строковый пришлось бы писать во флеш целиком при каждом
/// сохранении, а раздел под настройки — это две страницы стирания.
#[must_use]
pub trait SettingsStorage {
    /// Отказ флеша или повреждение данных в разделе.
    type Error;

    /// Самое длинное значение, которое хранилище запишет и прочитает, байт.
    ///
    /// Зависит от реализации: запись дополняется до слова флеша, и предел
    /// считается от настоящего слова носителя, а не от худшего среди чипов.
    /// Узел, который хранит значения известной длины, сверяет её с пределом
    /// `const`-проверкой.
    const MAX_VALUE: usize;

    /// Читает значение по ключу; `None` — ключ ещё не записан.
    ///
    /// Значение копируется в буфер вызывающего, и результат ссылается на него.
    /// Буфера хватает по размеру самого значения: другие записи раздела, даже
    /// длиннее, на чтение не влияют.
    ///
    /// # Errors
    ///
    /// Возвращает ошибку флеша, если чтение не удалось, ошибку данных, если
    /// раздел повреждён, или ошибку, если значение длиннее буфера, — обрезанного
    /// значения не бывает.
    async fn read<'a>(
        &mut self,
        key: u32,
        scratch: &'a mut [u8],
    ) -> Result<Option<&'a [u8]>, Self::Error>;

    /// Записывает значение, логически затирая предыдущее с тем же ключом.
    ///
    /// # Errors
    ///
    /// Возвращает ошибку флеша, если запись не удалась.
    async fn write(&mut self, key: u32, value: &[u8]) -> Result<(), Self::Error>;
}
