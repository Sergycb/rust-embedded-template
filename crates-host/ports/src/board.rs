//! Сведения о плате, на которой работает прошивка.
//!
//! Данные, а не трейт: у них нет поведения, которое стоило бы подменять в
//! тестах, — фейком служит любое значение структуры. Отдаёт их полем
//! `Board::info` крейт `bsp`, а пользуется тот, кто сообщает о себе наружу
//! (ответ хосту, лог старта).

/// Что прошивка знает о чипе, на котором запущена.
///
/// Причины последнего сброса здесь нет: в `embassy-stm32` для неё нет API, а
/// регистр флагов у каждого семейства свой. Частот только две — `sys` и
/// `hclk1`: их заполняют все семейные реализации `rcc`, остальной состав
/// `Clocks` генерируется под чип и в шаблоне неизвестен.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub struct ChipSpec {
    /// Имя чипа, выбранного при генерации проекта (`stm32f407ve`).
    pub chip: &'static str,
    /// Уникальный 96-битный номер экземпляра чипа — заводской, не меняется.
    pub uid: [u8; 12],
    /// Объём flash чипа в байтах — весь, а не раздел приложения.
    pub flash_size: u32,
    /// Частота ядра (`sys`), Гц; `None`, если HAL её не посчитал.
    pub sys_hz: Option<u32>,
    /// Частота шины AHB (`hclk1`), Гц; `None`, если HAL её не посчитал.
    pub hclk1_hz: Option<u32>,
}
