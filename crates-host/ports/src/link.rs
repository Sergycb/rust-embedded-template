//! Порт кадрового канала связи.
//!
//! Реализует проект в `crates-cross/bsp` поверх своей периферии; пользуются
//! им протоколы `domain`, у которых границы кадра задаёт сама линия, — Modbus
//! RTU в первую очередь.

/// Канал, который принимает и отправляет кадры целиком: границы кадра
/// определяет транспорт, а не содержимое.
///
/// Нужен там, где конец кадра — свойство линии: в Modbus RTU это пауза
/// между кадрами, и найти её может только тот, кто видит линию (на STM32 —
/// приём UART до простоя линии, `read_until_idle`, с аппаратным выводом DE
/// для RS-485). Протоколам, у которых границу задают сами данные (COBS,
/// префикс длины, заголовок MBAP у Modbus TCP), этот порт не нужен: они
/// работают поверх потока `embedded_io_async::{Read, Write}` — его уже
/// реализуют `BufferedUart`, USB CDC и TCP-сокет `embassy-net`.
///
/// Ошибка [`recv`](Self::recv) значит «потерян один кадр», а не «канал
/// умер»: шум, чётность, переполнение, кадр длиннее буфера. Протокол
/// отбрасывает такой кадр и ждёт следующий — поэтому вариантов ошибки порт
/// не различает, а реализация обязана после ошибки оставаться рабочей.
#[must_use]
pub trait FrameLink {
    /// Потеря кадра на линии: шум, чётность, переполнение аппаратного
    /// приёма, кадр длиннее буфера.
    type Error;

    /// Ждёт следующий кадр и кладёт его в `buf` — сколько угодно долго.
    ///
    /// Буфер отдаёт вызывающий, потому что результат ссылается прямо на
    /// него: кадр не копируется.
    ///
    /// Future можно бросить (таймаут ответа у master'а —
    /// `embassy_time::with_timeout`), и после этого реализация обязана
    /// начать следующий `recv` с границы кадра: недочитанный хвост
    /// брошенного кадра, разобранный как начало нового, дал бы мусор,
    /// который отсеет только CRC — и то не всегда.
    ///
    /// # Errors
    ///
    /// Возвращает ошибку линии, если кадр потерян или не помещается в `buf`;
    /// канал после этого остаётся рабочим.
    async fn recv<'a>(&mut self, buf: &'a mut [u8]) -> Result<&'a [u8], Self::Error>;

    /// Отправляет кадр целиком и возвращается, когда последний байт ушёл в
    /// линию.
    ///
    /// «Ушёл в линию», а не «лёг в буфер передатчика»: на полудуплексной
    /// RS-485 сразу после отправки линию отпускают на приём ответа, и
    /// освободить её раньше последнего стоп-бита — оборвать собственный кадр.
    ///
    /// # Errors
    ///
    /// Возвращает ошибку линии, если отправка не удалась.
    async fn send(&mut self, frame: &[u8]) -> Result<(), Self::Error>;
}
