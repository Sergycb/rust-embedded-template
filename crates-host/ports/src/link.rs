//! Порт кадрового канала связи и ошибка обмена кадрами.
//!
//! Канал ([`FrameLink`]) реализуют адаптеры `adapters` над транспортами
//! платы: кадрирование потока байтов или датаграммы.
//! Что делать с принятым кадром, решает протокол, а не канал: протокол не
//! знает, какой канал под ним.
// {%- if has_modbus == "true" %}
//! Modbus slave — узел `domain::server` над [`FrameLink`].
// {%- endif %}
// {%- if has_protobuf == "true" %}
//! protobuf хоста — узел `domain::protobuf` над [`FrameDuplex`].
// {%- endif %}

/// Канал, который принимает и отправляет кадры целиком: границы кадра
/// определяет транспорт или адаптер под портом, а не протокол.
///
/// Нужен потому, что протокол не обязан разграничивать сообщения сам.
// {%- if has_protobuf == "true" %}
/// Так у protobuf (официальная документация: «the Protobuf wire format is not
/// self-delimiting»): склеенные сообщения он молча сливает в одно.
// {%- endif %}
/// Потоку байтов (`embedded_io_async::{Read, Write}`) границы даёт адаптер
/// кадрирования; интерфейсу, у которого они есть (датаграмма), — он сам.
///
/// Ошибки делятся на два случая ([`LinkError`]): потерян один кадр —
/// протокол работает дальше, — или канал закрыт либо отказал. В обоих
/// случаях узел пишет в лог и сразу зовёт снова, а переждать отказ и
/// восстановить канал — дело реализации, на следующем вызове: принять новое
/// соединение, заново привязать сокет, а нечего — выдержать паузу,
/// прежде чем снова вернуть ошибку; канал, отвечающий ошибкой на каждый
/// вызов без ожидания, крутил бы узел, не отдавая исполнитель. Реализация,
/// которой восстанавливать нечего, закрытым канал не объявляет.
#[must_use]
pub trait FrameLink {
    /// Причина потери кадра или отказа канала.
    type Error;

    /// Ждёт следующий кадр, кладёт его в начало [`buffer`](Self::buffer) и
    /// возвращает длину — сколько угодно долго.
    ///
    /// Буфер — свой у канала, а не параметр: размер кадра задаёт тот, кто
    /// собирает канал (сколько места нужно сверх кадра — CRC адаптера, —
    /// знает только реализация), и узел протокола получает канал вместе с
    /// буфером, одним объектом. Длина, а не срез — как у `recv_from` сокета:
    /// срез держал бы заимствование канала, и автомат узла не смог бы
    /// передать кадр в действие, которому нужен `&mut self`.
    ///
    /// Future можно бросить (таймаут, `select`), и после этого реализация
    /// обязана начать следующий `recv` с границы кадра — или продолжить
    /// брошенный кадр с того же места ([`FrameDuplex`] обязан именно это):
    /// недочитанный хвост брошенного кадра, разобранный как начало нового,
    /// дал бы мусор.
    ///
    /// # Errors
    ///
    /// [`LinkError::Lost`] — кадр потерян (битый, обрезанный, длиннее буфера,
    /// помеха на линии), канал рабочий; [`LinkError::Down`] — канал закрыт
    /// или отказал.
    async fn recv(&mut self) -> Result<usize, LinkError<Self::Error>>;

    /// Буфер кадра — один на приём и передачу: после `recv` в его начале
    /// принятый кадр, перед `send` вызывающий кладёт туда кадр ответа.
    ///
    /// Один, а не два: протокол разбирает запрос в свои типы раньше, чем
    /// собирает ответ, и второй буфер стоял бы пустым.
    fn buffer(&mut self) -> &mut [u8];

    /// Отправляет кадр `buffer()[..len]` целиком и возвращается, когда
    /// последний байт ушёл в линию.
    ///
    /// «Ушёл в линию», а не «лёг в буфер передатчика»: на полудуплексной
    /// RS-485 сразу после отправки линию отпускают на приём ответа, и
    /// освободить её раньше последнего стоп-бита — оборвать собственный кадр.
    ///
    /// # Errors
    ///
    /// [`LinkError::Lost`] — этот кадр не отправлен (не помещается в кадр
    /// транспорта), канал рабочий; [`LinkError::Down`] — канал закрыт или
    /// отказал.
    ///
    /// # Panics
    ///
    /// Если `len` больше буфера — ошибка вызывающего.
    async fn send(&mut self, len: usize) -> Result<(), LinkError<Self::Error>>;
}

/// Канал, который узел гоняет наперегонки с другими источниками: приём кадра
/// и отправка не мешают друг другу.
///
/// Нужен узлу, который ждёт кадр наперегонки с другим своим входом
// {%- if has_protobuf == "true" %}
/// (узел `PROTOBUF`: под сообщения по инициативе устройства — события,
/// телеметрию — у него будет второй вход; ответ он и сейчас кодирует в свой
/// буфер)
// {%- endif %}
/// — то, что надо отправить, приходит посреди приёма следующего кадра и
/// уходит, не трогая принятое.
/// Отсюда два обязательства сверх [`FrameLink`]:
///
/// * брошенный [`recv`](FrameLink::recv) не теряет ничего — ни принятые байты
///   кадра, ни сам кадр: следующий `recv` продолжает с того же места;
/// * [`send_from`](Self::send_from) отправляет кадр из буфера вызывающего, и
///   буфер канала, где может лежать недочитанный кадр, остаётся как был.
#[must_use]
pub trait FrameDuplex: FrameLink {
    /// Отправляет кадр `frame` целиком — как [`send`](FrameLink::send), но из
    /// буфера вызывающего.
    ///
    /// # Errors
    ///
    /// [`LinkError::Lost`] — кадр не отправлен (не помещается в кадр
    /// транспорта), канал рабочий; [`LinkError::Down`] — канал закрыт или
    /// отказал.
    async fn send_from(&mut self, frame: &[u8]) -> Result<(), LinkError<Self::Error>>;
}

/// Почему [`FrameLink`] не принял или не отправил кадр.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub enum LinkError<E> {
    /// Кадр потерян, канал рабочий: следующий вызов обработает следующий
    /// кадр.
    Lost(E),
    /// Канал закрыт или отказал (соединение разорвано, поток кончился).
    Down(E),
}
