//! Порт шины CAN.
//!
//! Реализует `crates-cross/bsp`: в шаблоне — заглушка `bsp::stub::Can` (кадр —
//! `embassy_stm32::can::Frame`, он уже реализует `embedded_can::Frame`); свой
//! тип над контроллером проект ставит по рецепту `docs/modules/bsp-can.md`.
// {%- if has_canopen == "true" %}
//! Пользуется им узел CANopen `domain::canopen`.
// {%- endif %}

use crate::LinkError;

/// Шина CAN: принимает и отправляет кадры.
///
/// Кадр CAN, в отличие от потока байтов, ограничен самим железом —
/// кадрировать ничего не нужно; ошибки — те же два случая
/// [`LinkError`], что у кадрового канала: потерян кадр
/// (ошибка шины, переполнение FIFO) или шина недоступна (bus-off, контроллер
/// отказал).
///
/// На ошибку узел пишет в лог и сразу зовёт снова — переждать отказ дело
/// реализации: шина в bus-off или на линии с помехой не должна вернуть
/// ошибку снова без ожидания, иначе узел крутил бы цикл, не отдавая
/// исполнитель. Паузу реализация выдерживает в начале следующего
/// [`recv`](Self::recv), а не в самой ошибке: узел бросает `recv` по такту, и
/// пауза внутри ошибки, отменённая тактом, не дала бы ошибке дойти до лога.
#[must_use]
pub trait CanBus {
    /// Кадр шины.
    type Frame: embedded_can::Frame;
    /// Причина потери кадра или отказа шины.
    type Error;

    /// Ждёт следующий кадр — сколько угодно долго.
    ///
    /// Future обязан быть безопасным для отмены: узел ждёт кадр наперегонки
    /// с тактом таймера и бросает ожидание, когда такт наступает раньше.
    /// Брошенный `recv` не должен терять кадр, который уже принят
    /// контроллером, — так ведёт себя приём из FIFO `embassy-stm32`.
    ///
    /// # Errors
    ///
    /// [`LinkError::Lost`] — кадр потерян, шина рабочая; [`LinkError::Down`] —
    /// шина недоступна.
    async fn recv(&mut self) -> Result<Self::Frame, LinkError<Self::Error>>;

    /// Отправляет кадр; возвращается, когда кадр принят в очередь передачи
    /// контроллера.
    ///
    /// Места в очереди не ждёт вечно: на шине, где кадр никто не подтверждает
    /// (плата одна, трансивер обесточен, bus-off), оно не освободится никогда,
    /// и узел встал бы внутри отправки. Срок ожидания реализация ставит сама
    /// (`embassy_time::with_timeout`) и по его истечении возвращает
    /// [`LinkError::Lost`].
    ///
    /// # Errors
    ///
    /// [`LinkError::Lost`] — кадр не отправлен, шина рабочая;
    /// [`LinkError::Down`] — шина недоступна.
    async fn send(&mut self, frame: &Self::Frame) -> Result<(), LinkError<Self::Error>>;
}
