//! Порт шины CAN.
//!
//! Реализует `crates-cross/bsp` поверх CAN-контроллера чипа (кадр
//! `embassy-stm32` уже реализует `embedded_can::Frame`); пользуется им узел
//! CANopen `domain::canopen`.

use crate::LinkError;

/// Шина CAN: принимает и отправляет кадры.
///
/// Кадр CAN, в отличие от потока байтов, ограничен самим железом —
/// кадрировать ничего не нужно; ошибки — те же два случая, что у
/// [`FrameLink`](crate::FrameLink): потерян кадр (ошибка шины, переполнение
/// FIFO) или шина недоступна (bus-off, контроллер отказал).
///
/// На ошибку узел пишет в лог и сразу зовёт снова — переждать отказ дело
/// реализации: шина, отвечающая ошибкой на каждый вызов без ожидания
/// (bus-off, помеха), обязана сделать паузу, прежде чем вернуть ошибку, иначе
/// узел крутил бы цикл, не отдавая исполнитель.
#[must_use]
pub trait CanBus {
    /// Кадр шины.
    type Frame: embedded_can::Frame;
    /// Причина потери кадра или отказа шины.
    type Error;

    /// Ждёт следующий кадр — сколько угодно долго.
    ///
    /// Future обязан быть безопасным для отмены: узел ждёт кадр наперегонки
    /// с тактом таймера и бросает ожидание, когда такт наступает раньше.
    /// Брошенный `recv` не должен терять кадр, который уже принят
    /// контроллером, — так ведёт себя приём из FIFO `embassy-stm32`.
    ///
    /// # Errors
    ///
    /// [`LinkError::Lost`] — кадр потерян, шина рабочая; [`LinkError::Down`] —
    /// шина недоступна.
    async fn recv(&mut self) -> Result<Self::Frame, LinkError<Self::Error>>;

    /// Отправляет кадр; возвращается, когда кадр принят в очередь передачи
    /// контроллера.
    ///
    /// # Errors
    ///
    /// [`LinkError::Lost`] — кадр не отправлен, шина рабочая;
    /// [`LinkError::Down`] — шина недоступна.
    async fn send(&mut self, frame: &Self::Frame) -> Result<(), LinkError<Self::Error>>;
}
