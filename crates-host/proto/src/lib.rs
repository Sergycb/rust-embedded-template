#![cfg_attr(not(test), no_std)]

//! Схема протокола обмена с хостом и типы её сообщений, сгенерированные
//! `micropb-gen` из `proto/host.proto` (см. `build.rs`).
//!
//! Отдельным крейтом, а не модулем `domain`: генерация со своим `build.rs` и
//! зависимостями сборки живёт в одном месте, а `domain` своих типов не
//! заводит — узел HOST работает с любыми сообщениями, реализующими
//! `micropb::MessageDecode`/`MessageEncode`.
//!
//! Пример схемы — конверт `Request`/`Response` с `request_id`; проект
//! заменяет его своим.

/// Сгенерированные типы пакета `host`.
pub mod host;

pub use host::*;

/// Контейнеры полей сообщений (`heapless::String`, `heapless::Vec`) — тем,
/// кто строит сообщения, нужна ровно та версия, что у генератора.
pub use heapless;
