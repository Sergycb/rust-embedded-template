/// Нижняя граница: короче этого `IndependentWatchdog` считает окно
/// перезагрузки как `0u16 - 1`. В release (`overflow-checks = false`) это
/// молча даёт максимальное окно вместо минимального — то есть сторож,
/// который якобы стоит на 100 мкс, на деле терпит полсекунды.
const MIN_TIMEOUT_US: u32 = 1_000;

/// Наибольший делитель тактов LSI, который умеет IWDG.
const MAX_PRESCALER: u32 = 256;
/// Наибольшее значение счётчика перезагрузки (`MAX_RL` в `embassy_stm32::wdg`).
const MAX_RELOAD: u32 = 0xFFF;

/// Верхняя граница: дальше не хватает прескалера.
///
/// Считается ровно той же формулой и от той же `LSI_FREQ`, что и внутри
/// embassy (`get_timeout_us(256, MAX_RL)` в `wdg/mod.rs`), и это не
/// педантизм: наша граница обязана быть НЕ ВЫШЕ его предела. Иначе assert
/// ниже пропускает таймаут, на котором embassy сама уходит в панику через
/// `unwrap!`, — а в release паника это сброс, то есть ровно тот цикл
/// перезагрузок, который assert и должен предотвращать.
///
/// Здесь стояло `30_000_000` «с запасом вниз от 32 кГц», и рассуждение было
/// перевёрнуто: частота LSI по семействам разная (40 кГц у F0/F1/F3, 32 кГц у
/// остальных — `rcc/bd.rs`), но выше частота — КОРОЧЕ максимальное окно. На
/// 40 кГц предел 26.2 с, то есть таймаут 28 с проходил проверку и падал
/// внутри embassy.
const MAX_TIMEOUT_US: u32 = 1_000_000 * (MAX_RELOAD + 1) / (LSI_FREQ.0 / MAX_PRESCALER);

pub struct Iwdg<T: Instance + 'static>(IndependentWatchdog<'static, T>);

impl<T: Instance + 'static> Iwdg<T> {
    /// Запускает сторожевой таймер.
    ///
    /// Запускает сразу, а не отдельным методом, и это не упрощение ради
    /// краткости: `IndependentWatchdog` после `new` ещё не сторожит, и
    /// раздельные шаги дают состояние, в котором watchdog вроде бы есть, а
    /// система не защищена — забыть вторую строку легко, заметить нечем.
    ///
    /// Выключить его после этого нельзя: IWDG останавливается только сбросом.
    ///
    /// **Отсчёт начинается здесь, а кормить его начнёт только граф задач** —
    /// после `put` и `spawn_all`, да и то не раньше первого тика
    /// `check_every`. Всё, что стоит между этим вызовом и запуском графа,
    /// обязано уложиться в таймаут: скажем, в проекте с подписью там же идёт
    /// проверка образа (`salty` со `slow-motion` — порядка сотни миллионов
    /// тактов) и запись во flash при `mark_booted()`. Не уложитесь — плата
    /// уйдёт в перезагрузки молча, без единой строки в логе. Ровно поэтому
    /// вызов вынесен из `Board::init` в `main`, вплотную к `put`, — а свою
    /// долгую инициализацию ставьте ВЫШЕ него, а не между ним и `spawn_all`.
    ///
    /// Второе соотношение, которое надо держать: аппаратный таймаут должен
    /// быть **больше** таймаута узла в графе плюс `check_every`. Иначе железо
    /// сбросит МК раньше, чем программный мультиплексор заметит зависшую
    /// задачу, и вся диагностика `supervisor` окажется мёртвым кодом. Обратная
    /// сторона: худшее время «задача зависла → сброс» равно СУММЕ обоих
    /// таймаутов, потому что отсчёт железа начинается с последнего `feed()`.
    ///
    /// # Паника
    ///
    /// Если таймаут вне диапазона, который IWDG умеет отсчитать. Проверка
    /// стоит здесь, а не оставлена embassy, по разным причинам с двух краёв:
    /// сверху `IndependentWatchdog::new` паникует сам (а на release паника —
    /// это сброс, то есть цикл перезагрузок из-за опечатки в конфигурации),
    /// снизу же он молча вычисляет `0u16 - 1` и ставит МАКСИМАЛЬНОЕ окно
    /// вместо запрошенного минимального — с `overflow-checks = false` в
    /// release это не заметит никто.
    pub fn new(peripheral: Peri<'static, T>, timeout: Duration) -> Self {
        let micros = u32::try_from(timeout.as_micros())
            .expect("таймаут IWDG не помещается в u32 микросекунд");
        assert!(
            (MIN_TIMEOUT_US..=MAX_TIMEOUT_US).contains(&micros),
            "таймаут IWDG вне диапазона: {micros} мкс при допустимых {MIN_TIMEOUT_US}..\
             ={MAX_TIMEOUT_US}",
        );
        let mut watchdog = IndependentWatchdog::new(peripheral, micros);
        watchdog.unleash();
        Self(watchdog)
    }
}

impl<T: Instance + 'static> HardwareWatchdog for Iwdg<T> {
    fn feed(&mut self) {
        self.0.pet();
    }

    fn trigger_reset(&mut self) -> ! {
        // Просто перестаём кормить и ждём. Не `SCB::sys_reset()`, хотя тот
        // сработал бы быстрее: сброс должен прийти именно от сторожевого
        // таймера, иначе в регистре флагов сброса он неотличим от
        // программного перезапуска — а разница ровно та, ради которой
        // watchdog и ставят («устройство зависло» против «его попросили
        // перезапуститься»).
        loop {
            cortex_m::asm::wfi();
        }
    }
}
