    /// Проверяет подпись принятого образа и, если она верна, просит bootloader
    /// поменять разделы местами на следующем сбросе. Сам сброс — за
    /// вызывающим: только он знает, когда устройство можно перезапустить.
    ///
    /// `signature` и `length` приезжают вместе с образом по вашему каналу, а
    /// берутся из сборки: `cargo xtask build` кладёт рядом с ELF сырой
    /// `app.bin`, его подпись `app.bin.sig` и печатает длину. Подписан при
    /// этом не образ, а его SHA-512: так проверяет `embassy-boot`, так же
    /// считает и хостовая сторона.
    ///
    /// Проверка читает весь раздел и считает по нему хеш, то есть занимает
    /// заметное время (портируемая реализация ed25519 — порядка сотни
    /// миллионов тактов). Случается это один раз перед перезагрузкой.
    ///
    /// Не прошла проверка — разделы не меняются местами, и устройство
    /// продолжает работать на текущем образе. Именно поэтому подпись
    /// проверяется здесь, а не в bootloader'е: тот прыгает безусловно (см.
    /// README, раздел «Bootloader»), а отвергнуть чужой образ нужно ДО того,
    /// как он стал активным.
    pub fn verify_and_mark_updated(
        &mut self,
        signature: &[u8; 64],
        length: u32,
    ) -> Result<(), UpdateError> {
        // Длина проверяется ПЕРВОЙ, и порядок здесь не косметика. Присылает
        // её тот же канал, что и образ, то есть доверять ей нельзя, а
        // `verify_and_mark_updated` в embassy-boot начинается с
        // `assert!(update_len <= dfu.capacity())` — то есть с паники, а на
        // release-профиле паника это сброс: одно кривое число уводило бы
        // устройство в цикл перезагрузок.
        //
        // Порядок и отдельный вид ошибки — оба ради проверяемости, и это не
        // теория: тест, где обе защиты возвращали `BadState`, оставался
        // зелёным после удаления этой (проверено удалением на живой плате).
        // В шаблоне ключ по умолчанию нулевой, поэтому проверь мы сначала его
        // — сюда бы просто не доходило; а вернись отсюда тот же `BadState` —
        // тест не отличил бы одну защиту от другой.
        //
        // Сверяется с размером `ACTIVE`, а он меньше `DFU` — то есть проверка
        // строже, чем `assert!` внутри embassy-boot, и заодно отсекает образ,
        // который в раздел приёма влез бы, а при обмене оказался обрезан (см.
        // `max_image_len`).
        if length > max_image_len() {
            return Err(Error::Flash(NorFlashErrorKind::OutOfBounds).into());
        }
        // Версия — ПЕРЕД подписью, и это не оплошность. Читается она из
        // непроверенных ещё байтов, но подделать её нельзя: четыре байта
        // версии лежат внутри того, что подписано, и хеш считается по ним
        // тоже. Соврать про версию — значит не пройти подпись строчкой ниже.
        //
        // После подписи проверять поздно: `verify_and_mark_updated` при
        // успехе сразу помечает разделы к обмену, и отказ по версии пришёлся
        // бы уже на принятый образ.
        //
        // ПЕРЕД проверкой ключа — иначе защиту от отката нечем было бы
        // проверить: в шаблоне ключ нулевой, до версии дело просто не дошло
        // бы, и target-тест `ota_rejects_an_older_image` был бы вечно красным
        // — сколько бы ни работала сама проверка.
        //
        // С длиной причина другая, хотя вывод тот же: там обе защиты сначала
        // возвращали `BadState`, и тест оставался ложно-ЗЕЛЁНЫМ (см.
        // комментарий выше). Здесь у отказа собственный вариант
        // `UpdateError::Rollback`, так что спутать его не с чем.
        self.refuse_rollback(length)?;
        // Ключ не подставлен — отказ до криптографии. Нулевой ключ ed25519 не
        // «просто не совпадёт»: это точка малого порядка, для которой подпись
        // подделывается перебором за считанные попытки.
        if PUBLIC_KEY == [0; 32] {
            return Err(Error::BadState.into());
        }
        self.updater()
            .verify_and_mark_updated(&PUBLIC_KEY, signature, length)?;
        Ok(())
    }
