    /// Просит bootloader поменять разделы местами на следующем сбросе.
    /// Сам сброс — за вызывающим: только он знает, когда устройство можно
    /// перезапустить.
    ///
    /// Проверки длины образа здесь нет, и это не упущение: длину этот вызов не
    /// принимает вовсе. Выход за границу раздела ловит сама запись: `Ota::write`
    /// пишет прямо в раздел, а тот сверяет `offset + len` со своим размером и
    /// отвечает ошибкой. Ручная проверка нужна только подписанному варианту: там
    /// `verify_and_mark_updated` начинается с `assert!(update_len <=
    /// dfu.capacity())`, то есть с паники, а на release-профиле паника — сброс.
    ///
    /// Оговорка на случай совсем недоверенного канала: смещения на границе
    /// `u32` до проверок не доходят — и `embassy-boot`, и драйвер флеша
    /// складывают `offset + len` обычным `+`, а `[profile.dev]`/`[profile.test]`
    /// собираются с `overflow-checks = true`, то есть такое сложение паникует
    /// (в release — молча заворачивается). Приходит смещение из вашего
    /// протокола, так что отсекать заведомую чушь дешевле там же, где вы
