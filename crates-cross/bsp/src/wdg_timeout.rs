//! Аппаратный таймаут сторожа — один на приложение и bootloader.
//!
//! Отдельным файлом без зависимостей, потому что его читают двое: `bsp::wdg`
//! и `crates-cross/boot` (через `#[path]`, bootloader от `bsp` не зависит).

/// Аппаратный таймаут сторожа платы — параметр типа `bsp::wdg::BoardWatchdog`.
///
/// Десять секунд — величина не измеренная, а выведенная из цепочки, которую
/// шаблон обязан удержать целиком: потолок backoff'а (5 с) < таймаут узла
/// (`domain::app::WATCHDOG`, 7 с) < этот таймаут минус `WATCHDOG_CHECK_EVERY`.
/// Обе цифры слева живут во фрагменте узла (`domain::app`) и связаны там
/// `const`-assert'ом; `WATCHDOG_CHECK_EVERY` — в `app/src/graph.rs`. Правьте
/// их только вместе. Диапазону IWDG значение удовлетворяет на любом
/// семействе (предел — 26.2 с при LSI 40 кГц, см. `MAX_TIMEOUT_US` в `bsp::wdg`).
///
/// **В микросекундах и `u32`, а не `Duration`, потому что это аргумент
/// const-параметра.** Той же цифрой `Iwdg::new` заряжает железо и
/// `HardwareWatchdog::HARDWARE_TIMEOUT` объявляет бюджет — второго
/// источника истины не возникает по построению, и ровно этого требует
/// документация константы в `watchdog`. Побочный выигрыш: половину правого
/// звена цепочки проверяет компилятор — `supervisor_graph!` эмитит
/// `const`-assert «`check_every` строго короче `HARDWARE_TIMEOUT`» (таймаут
/// узла в него не входит намеренно, см. `Iwdg::new`), а выход самой цифры за
/// диапазон IWDG становится ошибкой сборки вместо паники на плате.
///
/// Второе требование к нему — пережить всё, что стоит между взведением
/// сторожа и первым кормлением от тикера графа; что там окажется в
/// конкретном проекте, шаблон не знает.
///
/// Той же цифрой взводит сторож release-bootloader (`crates-cross/boot`), и у
/// неё там два своих требования: пережить самую долгую одну операцию флеша
/// при обмене разделов (стирание страницы — крупнейшего сектора, секунды на
/// F4/H7; между операциями сторож кормится) и весь путь приложения от прыжка
/// до тикера графа. Одна цифра на оба сторожа — не удобство: приложение
/// перезаписывает прескалер уже идущего счётчика, и разные таймауты
/// масштабировали бы остаток до первого кормления (docs/watchdog.md).
///
/// Уменьшать её имеет смысл вместе с ответом на вопрос «через сколько
/// зависшее устройство обязано вернуться в работу», и не ниже суммы таймаута
/// узла и `check_every` графа — иначе железо сбросит МК раньше, чем
/// программный мультиплексор заметит зависшую задачу, и вся диагностика
/// `supervisor` окажется мёртвым кодом.
pub const HW_TIMEOUT_US: u32 = 10_000_000;
