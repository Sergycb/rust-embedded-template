    /// Неверная подпись не проходит — проверка идёт на самом чипе.
    ///
    /// Что именно доказывает тест, зависит от того, подставлен ли открытый
    /// ключ. Пока в `PUBLIC_KEY` нули (значение по умолчанию), отказ приходит
    /// раньше криптографии — из явной защиты в `Ota`, и тест стережёт её:
    /// нулевой ключ ed25519 это точка малого порядка, подпись для неё
    /// подделывается перебором. Как только ключ подставлен (`cargo xtask
    /// ota-key`), тот же тест начинает проверять главное — что `salty`
    /// действительно считается на этом ядре и отвергает мусор.
    ///
    /// Обновление при этом не запрашивается ни в одном случае: `embassy-boot`
    /// зовёт `mark_updated()` только после успешной проверки. Плата остаётся
    /// на текущем образе.
    #[test]
    fn ota_rejects_a_bad_signature(mut board: Board) {
        use bsp::ota::Error;

        // Нули — заведомо не подпись: ни для какого ключа и сообщения.
        let signature = [0u8; 64];

        // Длина заведомо меньше раздела, иначе отказ пришёл бы от проверки
        // длины, а не от подписи.
        assert!(
            board.ota.verify_and_mark_updated(&signature, 64).is_err(),
            "неверная подпись принята — по OTA прошёл бы чужой образ"
        );

        // А это уже про длину. Сверяется КОНКРЕТНЫЙ вид ошибки, и это не
        // придирка: пока обе защиты возвращали `BadState`, тест оставался
        // зелёным даже после удаления той, что проверяет длину (проверено
        // удалением на живой плате). Отказ по незаполненному ключу — тоже
        // ошибка, и `is_err()` его не отличает.
        //
        // Зачем защита вообще: длина приходит из недоверенного канала, а
        // внутри embassy-boot на ней стоит `assert!(update_len <=
        // dfu.capacity())`, то есть паника. На release-профиле паника это
        // сброс — устройство уходило бы в цикл перезагрузок от одного кривого
        // пакета.
        let refused = board.ota.verify_and_mark_updated(&signature, u32::MAX);
        assert!(
            matches!(refused, Err(Error::Flash(_))),
            "длина больше раздела DFU должна отвергаться отдельной ошибкой"
        );
    }
