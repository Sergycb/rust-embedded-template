//! Ethernet-драйвер чипа — заглушка до Ethernet-блока платы.
//!
//! Стек `embassy-net` и его фоновую работу собирает `bsp`
//! (`crates-cross/bsp/src/ethernet.rs`): от чипа они не зависят, и устройство —
//! единственное, что `cpu` сюда отдаёт. MAC — из заводского номера чипа.

/// Сетевое устройство чипа — пока заглушка, до Ethernet (см. модуль).
pub type Ethernet = adapters_hw::net::stub::Device;

/// Собирает устройство с MAC из заводского номера `uid`: локально
/// администрируемым, без группового — у каждой платы свой и постоянный.
pub(crate) fn new(uid: [u8; 12]) -> Ethernet {
    defmt::warn!("cpu: Ethernet не подключён — сеть без линка, протокол ждёт впустую");
    Ethernet::new(mac_from_uid(uid))
}
