//! # Питание от батареи: STOP между задачами
//!
//! Исполнитель по умолчанию засыпает в `WFE` — ядро стоит, но регуляторы и
//! тактирование работают, и это единицы миллиампер. Для устройства на батарее
//! нужен режим STOP, где остаётся жить только то, что вы попросили: там речь
//! про единицы микроампер. `embassy-stm32` умеет уходить в STOP прямо из
//! главного цикла, но включается это не одной фичей — переключается сам
//! исполнитель, и шаблон намеренно не делает этого за вас (нужен вывод под
//! часовой кварц, а есть он не на каждой плате).
//!
//! Что менять, если вы за это взялись:
//!
//! ```ignore
//! // 1. crates-cross/Cargo.toml, embassy-stm32: + "low-power", + "executor-thread",
//! //    + драйвер времени на LPTIM вместо TIM (например "time-driver-lptim1").
//! // 2. Там же, embassy-executor: УБРАТЬ "platform-cortex-m" — иначе
//! //    исполнителей окажется два, и линковка не пройдёт.
//! // 3. main.rs: указать исполнителя явно.
//! #[embassy_executor::main(
//!     executor = "embassy_stm32::executor::Executor",
//!     entry = "cortex_m_rt::entry"
//! )]
//! async fn main(spawner: Spawner) { /* как было */ }
//! ```
//!
//! Три вещи, на которых спотыкаются:
//!
//! * **Драйвер времени обязан пережить STOP.** `TIM` в этом режиме
//!   останавливается — вместе с ним встанет `embassy-time`, и устройство
//!   проснётся не по таймеру, а никогда. Отсюда `time-driver-lptim*`: LPTIM
//!   тикает от LSE/LSI, которые в STOP живут.
//! * **Занятая периферия не пускает в STOP.** `sleep()` смотрит на состояние
//!   RCC: пока жив объект `I2c`/`Usart`, чип останется в обычном сне. Держать
//!   их в статике «чтобы не пересоздавать» — ровно то, что съест экономию;
//!   создавайте на время обмена и роняйте.
//! * **Сторож, скорее всего, не спит.** IWDG тикает от LSI, а тот в STOP
//!   живёт: запущенный сторож продолжает считать и разбудит устройство
//!   сбросом, если узел графа с `watchdog:` уснёт дольше таймаута. У части
//!   семейств поведение переключается опционным байтом (`IWDG_STOP`), но по
//!   умолчанию рассчитывайте на худшее: просыпайтесь чаще таймаута или не
//!   отдавайте такой узел под длинный сон. Остановить уже запущенный IWDG
//!   нельзя — это его свойство, а не недосмотр (см. `bsp::wdg`).
//!
//! # PERSIST и PANIC: данные, переживающие сброс
//!
//! Если у чипа хватило RAM, генерация отрезала от её конца кусок и поделила на
//! два региона: `PANIC` — под дамп `panic-persist` (им занят
//! `#[panic_handler]` в `main.rs`, трогать не надо) и `PERSIST` — под данные,
//! которые должны пережить сброс. Оба живут в RAM, поэтому переживают
//! программный сброс, но не пропадание питания.
//!
//! **Начало `PERSIST` занято.** Первые два слова принадлежат счётчику запусков
//! (`bsp::persist::BootCount`, порт `ports::BootCounter`): слово магии и само
//! значение. Своё кладите после них — смещение `PERSIST_RESERVED` в примере
//! ниже. Писать в первые восемь байт нельзя: счётчик собьётся, а вместе с ним
//! упадёт host-target тест `firmware_runs_and_counts_boots_across_resets`,
//! который читает то же место пробником.
//!
//! Адресуются они символами из `memory.x`, а не `link_section`-секцией, и это
//! важное ограничение, а не стиль. Своя секция в конце RAM ломает `flip-link`
//! (он уводит стек от переполнения в статические данные): тот считает занятую
//! часть RAM по адресам секций, видит секцию у самой верхней границы, решает,
//! что двигать стек некуда, и оставляет `_stack_start` в начале RAM. Прошивка
//! после этого не доживает до первой строки лога — первый же push уходит ниже
//! границы RAM, HardFault, LOCKUP. Абсолютные символы `flip-link` не смущают.
//!
//! Место таким данным — в `bsp`, рядом со счётчиком (`bsp/src/persist.rs`), и
//! наружу они уходят объектом за портом: приложению незачем знать ни адрес, ни
//! то, что за ним RAM. Набросок:
//!
//! ```ignore
//! unsafe extern "C" {
//!     static mut _persist_start: u8;
//!     static mut _persist_end: u8;
//! }
//!
//! /// Два слова в начале региона держит счётчик запусков — своё кладём после.
//! const PERSIST_RESERVED: usize = 2;
//!
//! /// Своя магия, отличающая «наши данные» от мусора, который оказался в RAM
//! /// при подаче питания. Ровно так же поступает panic-persist со своим
//! /// заголовком — и по той же причине: первый в жизни платы старт ничем не
//! /// отличается от любого другого.
//! const MAGIC: u32 = 0xC0FF_EE00;
//!
//! /// Например, счётчик неудачных попыток связи, переживающий сброс.
//! fn failures() -> u32 {
//!     let base = unsafe { (&raw mut _persist_start as *mut u32).add(PERSIST_RESERVED) };
//!     // SAFETY: регион PERSIST отведён под это в memory.x, первые
//!     // PERSIST_RESERVED слов заняты счётчиком запусков, а дальше кроме нас
//!     // никто не пишет. Адрес выровнен: начало региона кратно четырём (см.
//!     // bsp/src/persist.rs), смещение — целое число слов.
//!     unsafe {
//!         if base.read_volatile() == MAGIC {
//!             base.add(1).read_volatile()
//!         } else {
